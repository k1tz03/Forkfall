RACINES = {'i': 'A', 'I': 'A', 'i5': 'A', 'bVI': 'F', 'bVII': 'G', 'bVII5': 'G', 'iv': 'D'}
# les mesures : 'VI' = ♭VI trois temps puis ♭VII à vide (sol–ré : sous « do si », la quarte
# suspendue et sa résolution sonnent toutes deux justes ; un si tenu dans les nappes frotterait
# le do) ; 'VI7' = ♭VI puis ♭VII, deux temps chacun (la montée) ; 'VI75' = la même, ♭VII à
# vide (le motif lent du creux) ; 'VIIi' = ♭VII puis i ; 'VIi4' et 'ivi4' = ♭VI ou iv trois
# temps puis la quinte à vide (le canon de A2 : « do si » d'une voix, « la mi » de l'autre)
CELLULES = {'VI': ['bVI', 'bVI', 'bVI', 'bVII5'], 'VI7': ['bVI', 'bVI', 'bVII', 'bVII'],
            'VI75': ['bVI', 'bVI', 'bVII5', 'bVII5'], 'VIIi': ['bVII', 'bVII', 'i', 'i'],
            'VIi4': ['bVI', 'bVI', 'bVI', 'i5'], 'ivi4': ['iv', 'iv', 'iv', 'i5']}


def temps_accords(mesures):
    """Les accords temps par temps d'une suite de mesures."""
    sortie = []
    for c in mesures:
        sortie += CELLULES.get(c, [c] * 4)
    return sortie


def plages(temps):
    """Les accords temps par temps → [(début, durée, chiffre)], les temps égaux fusionnés."""
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def racine(ch, octave):
    """La fondamentale à l'octave dite ; jamais sous mi1 (le ré de iv remonte d'une octave)."""
    h = hauteur(f'{RACINES[ch]}{octave}')
    return h + 12 if h < hauteur('E1') else h


def voicing(ch, grave):
    """Les trois sons de l'accord, chacun au plus près au-dessus de `grave`."""
    g = hauteur(grave)
    sortie = set()
    for h in accord(ch, TON, octave=2):
        while h < g:
            h += 12
        sortie.add(h)
    return sorted(sortie)


# Les figures de l'ostinato : seize doubles croches (décalages en demi-tons sur la
# fondamentale du temps) et leurs accents. Groupées 3+3+2 ; la hauteur bouge sur les
# accents (l'octave, la quinte) et deux mesures de suite ne sont jamais pareilles.
FIG = {
    'a': ([0, 0, 0, 12, 0, 0, 7, 0, 0, 0, 0, 12, 0, 0, 7, 12], 'X x o X x o X x X x o X x o X o'),
    'b': ([0, 0, 0, 7, 0, 0, 12, 0, 0, 0, 0, 7, 0, 0, 12, 7], 'X x o X o x X x X o x X x o X x'),
    'c': ([0, 0, 12, 0, 0, 7, 0, 0, 0, 0, 12, 0, 0, 7, 12, 7], 'X o x X o x X o X o x X x o X x'),
    # la fanfare : 3+3+3+3+2+2, une autre respiration
    'd': ([0, 0, 0, 12, 0, 0, 7, 0, 0, 12, 0, 0, 0, 7, 0, 12], 'X x o X x o X x o X x o X x X x'),
    'e': ([0, 0, 0, 7, 0, 0, 12, 0, 0, 7, 0, 0, 12, 0, 7, 0], 'X o x X o x X o x X x o X o X x'),
}


def ostinato_mesure(racines4, fig, vel=84, temps=4):
    decal, acc = FIG[fig]
    acc = acc.split()
    notes = []
    for i in range(4 * temps):
        h = racines4[i // 4] + decal[i]
        v = {'X': vel + 22, 'x': vel, 'o': vel - 24}[acc[i]]
        notes.append(Note(h, i * 0.25, 0.25, v, 'staccato'))
    return Motif(notes, float(temps))


def moteur(s, piste, temps, octave, figs, vel=84, de=1, a=None, basse=None, vel_basse=96,
           derniere=4):
    """L'ostinato de doubles croches sur les fondamentales, de la mesure `de` à la mesure
    `a` comprise, les figures en rotation ; `basse` frappe les accents deux octaves
    dessous ; la dernière mesure s'arrête après `derniere` temps (un silence écrit)."""
    a = a or s.mesures
    for m in range(de, a + 1):
        r4 = [racine(c, octave) for c in temps[(m - 1) * 4:m * 4]]
        fig = figs[(m - 1) % len(figs)]
        nb = derniere if m == a else 4
        s.joue(piste, ostinato_mesure(r4, fig, vel, nb), a=s.m(m))
        if basse is not None:
            for i, c in enumerate(FIG[fig][1].split()[:4 * nb]):
                if c == 'X':
                    h = racine(temps[(m - 1) * 4 + i // 4], 1)
                    s.note(basse, h, s.m(m) + i * 0.25, 0.25, vel=vel_basse, art='staccato')


def nappe(s, piste, temps, grave, vel=70, art=None, de=0, jusqua=None):
    """Les accords tenus, de `de` à `jusqua` (en temps)."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d < de or d >= fin:
            continue
        for h in voicing(c, grave):
            s.note(piste, h, d, min(l, fin - d), vel=vel, art=art)


def fondamentales(s, piste, temps, octave, vel=80, art=None, de=0, jusqua=None, maxi=None):
    """La fondamentale de chaque accord, tenue (au plus `maxi` temps)."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d < de or d >= fin:
            continue
        l = min(l, fin - d, maxi or l)
        s.note(piste, racine(c, octave), d, l, vel=vel, art=art)


def cymbale_vers(s, fin, art='monte_4s', vel=96):
    """La cymbale suspendue qui enfle et culmine à `fin` (en temps)."""
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * SEC, secondes * SEC, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=90):
    """Un roulement (timbales, caisse claire) qui enfle de `de` à `a` (en temps)."""
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


# Les taïkos : deux hauteurs (la2 grave, mi3 aigu) qui dessinent le 3+3+2
