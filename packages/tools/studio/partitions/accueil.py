def tribune(s, de, jusqua, vel=100):
    """La tribune : grosse caisse sur 1 et 3, mains sur 2 et 4 (de la mesure `de` jusqu'à
    la position `jusqua`, en temps)."""
    s.batterie(gcaisse, 'K : X . . . . . . . x . . . . . . .', a=s.m(de), jusqua=jusqua, vel=vel)
    s.joue(mains, grille('. . . . X . . . . . . . X . . .', 'C4', vel=vel), a=s.m(de), jusqua=jusqua)


def la_phrase(s, de, unites, foule_vel=96, cors_vel=110, grave_vel=104, violons_chant=False):
    """La phrase chantée par tout le monde, unité par unité (deux mesures chacune, à
    partir de la mesure `de`) : 'motif', 'reponse', 'meche', 'montee'. La foule, les
    trombones et les violoncelles à la2–la3, les cors à l'octave, les violons (au grand
    sommet) deux octaves au-dessus des cors. Une unité qui commence à la première mesure
    de la section y entre sans son anacrouse (chantée au dernier temps de la section
    d'avant) ; les suivantes la prennent au 4ᵉ temps de la mesure qui précède."""
    formes = {'motif': MOTIF, 'reponse': REPONSE, 'meche': MECHE, 'montee': MONTEE}
    for k, u in enumerate(unites):
        m = de + 2 * k
        motif = formes[u]
        if m == 1:
            motif = motif.coupe(1, motif.longueur)
            a = 0
        else:
            a = s.m(m) - 1
        s.joue(cors, motif, a=a, vel=cors_vel)
        s.joue(trombones, motif.octave(-1), a=a, vel=grave_vel)
        s.joue(celles_chant, motif.octave(-1), a=a, vel=grave_vel - 6)
        s.joue(foule, motif.octave(-1), a=a, vel=foule_vel)
        if violons_chant:
            s.joue(violons, motif.octave(2), a=a, vel=grave_vel - 6, art='tenu')


def arpeges_montants(s, piste, grille_mes, depart, vel=88):
    """Les arpèges de violons qui montent : chaque mesure une vague de seize doubles
    croches dans l'accord, qui commence plus haut toutes les deux mesures ; la dernière
    mesure se tait au 4ᵉ temps."""
    for m, c in enumerate(grille_mes, start=1):
        b = depart + (m - 1) // 2
        rangs = [b, b + 1, b + 2, b + 3, b + 1, b + 2, b + 3, b + 4,
                 b + 2, b + 3, b + 4, b + 5, b + 3, b + 4, b + 5, b + 4]
        if m == len(grille_mes):
            rangs = rangs[:12]
        s.joue(piste, arpege(voicing(c, 'A3'), [str(r) for r in rangs], pas=0.25, vel=vel,
                             art='staccato'), a=s.m(m))


def pulsations(s, piste, grille_mes, grave, vel=96):
    """Les accords pulsés en croches, accents 3+3+2 ; la dernière mesure se tait au 4ᵉ temps."""
    for m, c in enumerate(grille_mes, start=1):
        rythme = 'X x x X x x X x' if m < len(grille_mes) else 'X x x X x x'
        for h in voicing(c, grave):
            s.joue(piste, grille(rythme, h, pas=0.5, vel=vel), a=s.m(m), art='staccato')


