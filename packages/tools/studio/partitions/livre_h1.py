def arpeges_montants(s, piste, grille_mes, depart, vel=88, de=1):
    """Les arpèges de violons qui montent : chaque mesure une vague de seize doubles croches dans
    l'accord, plus haute toutes les deux mesures ; la dernière mesure se tait au 4ᵉ temps."""
    for k, c in enumerate(grille_mes):
        m = de + k
        b = depart + k // 2
        rangs = [b, b + 1, b + 2, b + 3, b + 1, b + 2, b + 3, b + 4,
                 b + 2, b + 3, b + 4, b + 5, b + 3, b + 4, b + 5, b + 4]
        if k == len(grille_mes) - 1:
            rangs = rangs[:12]
        s.joue(piste, arpege(voicing(c, 'A3'), [str(r) for r in rangs], pas=0.25, vel=vel,
                             art='staccato'), a=s.m(m))


