def temps_accords(mesures):
    """Les accords temps par temps d'une suite de mesures."""
    sortie = []
    for c in mesures:
        sortie += CELLULES.get(c, [c] * 4)
    return sortie


def plages(temps):
    """Les accords temps par temps → [(début, durée, chiffre)], les temps égaux fusionnés."""
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def racine(ch, octave):
    """La fondamentale à l'octave dite ; jamais sous mi1."""
    h = hauteur(f'{RACINES[ch]}{octave}')
    return h + 12 if h < hauteur('E1') else h


def voicing(ch, grave, quinte=True):
    """Les sons de l'accord, chacun au plus près au-dessus de `grave` (la pédale de ré, « /1 »,
    reste à la basse : on ne la double pas dans les voix). `quinte=False` : la fondamentale et la
    tierce seulement (les nappes sous un air qui brode la quinte : la mèche ne frotte pas)."""
    g = hauteur(grave)
    sortie = set()
    sons = accord(ch.split('/')[0], TON, octave=2)
    if not quinte and len(sons) == 3 and not ch.split('/')[0].endswith('5'):
        sons = sons[:2]
    for h in sons:
        while h < g:
            h += 12
        sortie.add(h)
    return sorted(sortie)


def nappe_accords(s, piste, temps, grave, vel=70, art=None, de=0, jusqua=None, quinte=True):
    """Les accords tenus, de `de` à `jusqua` (en temps)."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        a = max(d, de)
        if a >= min(d + l, fin):
            continue
        for h in voicing(c, grave, quinte):
            s.note(piste, h, a, min(d + l, fin) - a, vel=vel, art=art)


def fondamentales(s, piste, temps, octave, vel=80, art=None, de=0, jusqua=None, maxi=None):
    """La fondamentale de chaque accord, tenue (au plus `maxi` temps)."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        a = max(d, de)
        l = min(d + l, fin) - a
        if l <= 0:
            continue
        s.note(piste, racine(c, octave), a, min(l, maxi or l), vel=vel, art=art)


def poum_pa(s, temps, de, a, vel=92, vel_pa=82, pa=(tromb_st,), grave='F3', basse=tuba, celli=True):
    """Le pas redoublé, de la mesure `de` à la mesure `a` comprises : la basse sur chaque temps,
    racine et quinte en alternance (le tuba, les violoncelles à l'octave), le « pa » sur les
    contretemps (les accords brefs des trombones, des cors)."""
    for m in range(de, a + 1):
        for b in range(4):
            c = temps[(m - 1) * 4 + b]
            r = racine(c, 1)
            # l'autre note : la quinte ; sur ré mineur, la tierce (fa), pour que la broderie de
            # l'air (si♭ sur le 2) ne frotte pas le la de la basse
            autre = r + 3 if c in ('i', 'i/1') else (r + 7 if r + 7 <= hauteur('A2') else r - 5)
            h = r if b % 2 == 0 else autre
            s.note(basse, h, s.m(m, b + 1), 0.6, vel=vel if b % 2 == 0 else vel - 8)
            if celli:
                s.note(celles, h + 12, s.m(m, b + 1), 0.5, vel=vel - 10, art='staccato')
            for p in pa:
                for x in voicing(c, grave):
                    s.note(p, x, s.m(m, b + 1.5), 0.4, vel=vel_pa)


def tchi(s, de, a, vel=74):
    """Les cymbales de la fanfare, étouffées, sur 2 et 4 (le « tchi » du pas redoublé), de la mesure
    `de` à `a` comprises."""
    for m in range(de, a + 1):
        for b in (2, 4):
            s.note(cymb_et, 'C4', s.m(m, b), 0.5, vel=vel - (6 if b == 2 else 0))


def tambour_nord(s, de, a, vel=100, toms=True):
    """Le tambour de la Nord, de la mesure `de` à `a` : BOUM sur le 1, « ta-ta » sur le 4 (le
    rythme de la tête, fu-si-BLE, frappé d'une mesure sur l'autre)."""
    for m in range(de, a + 1):
        s.joue(tambour, batterie('K : X . . . . . . . . . . . x . x .', vel=vel), a=s.m(m))
        if toms:
            s.joue(tom, grille('X . . . . . . . . . . . x . x .', ['D3', 'A2', 'A2'], vel=vel - 8), a=s.m(m))


# L'ostinato de la montée (le geste du thème principal) : seize doubles croches sur la
# fondamentale, groupées 3+3+2, l'octave et la quinte sur les accents ; deux mesures de suite ne
# sont jamais pareilles
FIG = {
    'a': ([0, 0, 0, 12, 0, 0, 7, 0, 0, 0, 0, 12, 0, 0, 7, 12], 'X x o X x o X x X x o X x o X o'),
    'b': ([0, 0, 0, 7, 0, 0, 12, 0, 0, 0, 0, 7, 0, 0, 12, 7], 'X x o X o x X x X o x X x o X x'),
    'c': ([0, 0, 12, 0, 0, 7, 0, 0, 0, 0, 12, 0, 0, 7, 12, 7], 'X o x X o x X o X o x X x o X x'),
}


def ostinato_mesure(racines4, fig, vel=84, temps=4):
    decal, acc = FIG[fig]
    acc = acc.split()
    notes = []
    for i in range(4 * temps):
        v = {'X': vel + 22, 'x': vel, 'o': vel - 24}[acc[i]]
        notes.append(Note(racines4[i // 4] + decal[i], i * 0.25, 0.25, v, 'staccato'))
    return Motif(notes, float(temps))


def ostinato_cordes(s, piste, temps, octave, figs, de, a, vel=84, derniere=4):
    """L'ostinato de doubles croches, de la mesure `de` à `a` comprises ; la dernière mesure
    s'arrête après `derniere` temps."""
    for m in range(de, a + 1):
        r4 = [racine(c, octave) for c in temps[(m - 1) * 4:m * 4]]
        nb = derniere if m == a else 4
        s.joue(piste, ostinato_mesure(r4, figs[(m - de) % len(figs)], vel, nb), a=s.m(m))


def bruissement(s, a, graine=3000, n=150, duree=0.55, vel=100):
    """Les trois mille cartons retournés d'un coup : des grains (le craquement, 1,5–4,8 kHz), des
    claques plus graves (le carton, 380 Hz–1,3 kHz), le souffle. Tiré d'une graine fixe."""
    rnd = random.Random(graine)
    for _ in range(n):
        u = rnd.random() ** 1.7               # serré au début : le geste de trois mille bras
        t = a + u * duree * SEC
        if rnd.random() < 0.62:
            f = rnd.uniform(1500, 4800) / 8.0
            s.note(cartons_grains, 69 + 12 * math.log2(f / 440.0), t, 0.012 * SEC,
                   vel=int(vel * rnd.uniform(0.55, 1.0)))
        else:
            f = rnd.uniform(380, 1300) / 2.0
            s.note(cartons_corps, 69 + 12 * math.log2(f / 440.0), t, 0.03 * SEC,
                   vel=int(vel * rnd.uniform(0.5, 0.95)))
    s.note(cartons_souffle, 'A4', a, duree * SEC, vel=vel)


def cymbale_vers(s, fin, art='monte_4s', vel=96):
    """La cymbale suspendue qui enfle et culmine à `fin` (en temps)."""
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * SEC, secondes * SEC, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=90):
    """Un roulement (timbales, caisse claire) qui enfle de `de` à `a` (en temps)."""
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def la_phrase(s, de, unites, foule_vel=96, cors_vel=104, grave_vel=100, clar_vel=None):
    """La phrase chantée par la tribune, unité par unité (deux mesures chacune, à partir de la
    mesure `de`) : la foule, les trombones et les violoncelles à ré3–si♭3, les cors (et les
    clarinettes) à l'octave. Une unité qui commence à la première mesure entre sans son
    anacrouse (chantée au dernier temps de la section d'avant)."""
    formes = {'motif': MOTIF, 'reponse': REPONSE, 'meche': MECHE}
    for k, u in enumerate(unites):
        m = de + 2 * k
        motif = formes[u]
        if m == 1:
            motif = motif.coupe(1, motif.longueur)
            a = 0
        else:
            a = s.m(m) - 1
        s.joue(foule, motif, a=a, vel=foule_vel)
        s.joue(trombones, motif, a=a, vel=grave_vel)
        s.joue(celles_chant, motif, a=a, vel=grave_vel - 8)
        s.joue(cors, motif.octave(1), a=a, vel=cors_vel)
        if clar_vel:
            s.joue(clar, motif.octave(1), a=a, vel=clar_vel)


