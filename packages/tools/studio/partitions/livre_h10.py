# --- D1 : deux téléphones (le sommet : les deux tonalités superposées) --------------------------------
@theme.section('D1', mesures=8)
def D1(s):
    # la couche de sol (en bas) sous le motif en sol des cors ; la couche de do♯ (en haut) sous le
    # motif en do♯ des trompettes, une mesure plus tard ; puis l'inverse (do♯ en bas, sol en
    # haut) : la basse lourde suit la couche du bas, et passe d'un téléphone à l'autre à m.5
    # (chaque couche sous son motif : la mèche sur ♭VI, la mesure d'avant sur i pour l'anacrouse)
    bas1 = grille(['Eb.F5', 'Gm', 'Gm', 'Gm.C#m'])
    haut1 = grille(['C#m', 'A.B5', 'C#m', 'C#m'])
    bas2 = grille(['A.B5', 'C#m', 'C#m', 'C#m'])
    haut2 = grille(['Gm', 'Eb.F5', 'Gm', 'Gm'])
    t_basse = bas1 + bas2
    nuances(s, cors='mf', trompettes='mf', trombones='mf', tuba='mf', choeur='mp', violons_tr='mf', basses='mf',
            celles='mf')
    s.note(arc.impact, 'G1', 0, 2, vel=116, art='impact')
    s.note(cymbales, 'C4', 0, 2, vel=106)
    s.note(gcaisse, 'K', 0, 1, vel=108)
    basse_lourde(s, t_basse, vel=106, figures=(0, 1))
    for m in range(1, 9):
        s.note(timbales, timbale(t_basse[int(s.m(m))]), s.m(m), 1, vel=100)
        s.note(gcaisse, 'K', s.m(m, 3), 1, vel=82)
    # le canon au triton : les cors en sol (la mèche dès le premier temps, sur l'impact), les
    # trompettes en do♯ une mesure plus tard ; puis l'inverse
    s.joue(cors, MOTIF_SOL.coupe(1, 8), a=0, vel=104)
    s.joue(trompettes, MOTIF_DOD4, a=s.m(1, 4), vel=98)
    s.joue(cors, MOTIF_DOD4, a=s.m(4, 4), vel=104)
    s.joue(trompettes, MOTIF_SOL4, a=s.m(5, 4), vel=98)
    s.joue(trombones, MOTIF_SOL.octave(-1).coupe(1, 8), a=0, vel=96)
    s.joue(trombones, MOTIF_DOD, a=s.m(4, 4), vel=96)
    # les deux couches d'accords : en bas, les fondamentales seules (tuba), l'harmonie dite par le
    # motif ; en haut, l'accord de l'autre tonalité (chœur, violons en trémolo)
    for d, l, c in plages(t_basse):
        s.note(tuba, BASSE[c], d, l, vel=86)
    # les deux tonalités séparées par le registre : la couche du haut à une neuvième au moins du
    # motif de l'autre tonalité (la bitonalité reste nette, elle ne « frotte » pas au milieu)
    nappe(s, choeur, haut1, 'G#4', vel=54, art='aah', jusqua=16)
    nappe(s, violons_tr, haut1, 'G#5', vel=60, jusqua=16)
    for d, l, c in plages(haut2):
        for h in voicing(c, 'C5'):
            s.note(choeur, h, 16 + d, l, vel=54, art='aah')
        for h in voicing(c, 'G5'):
            s.note(violons_tr, h, 16 + d, l, vel=60)
    # les deux sonneries croisées : une salve par mesure (la sonnerie, puis le silence), deux dans
    # les deux dernières mesures de chaque moitié (le glockenspiel, frappé à chaque croche
    # pendant seize secondes, aurait fatigué à la vingtième écoute)
    for m in range(1, 9):
        n = 2 if m in (3, 4, 7, 8) else 1
        fixe(s, m, fois=n, vel=84)
        clapet(s, m, fois=n, vel=84)
    s.note(cymbales, 'C4', s.m(5), 2, vel=96)


