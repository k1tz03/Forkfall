# --- C1 : l'escalier (une gamme qui perd une marche à chaque mesure) ----------------------------------
GAMME_SOL = ['G3', 'A3', 'Bb3', 'C4', 'D4', 'Eb4', 'F4', 'G4']
GAMME_DOD = ['C#4', 'D#4', 'E4', 'F#4', 'G#4', 'A4', 'B4', 'C#5']


def escalier(s, piste, gammes, de=1, a=None, vel=80, marches=8):
    """La gamme qui monte en croches et perd une marche par mesure (8, 7, 6…), de `de` à `a`."""
    a = a or s.mesures
    for k, m in enumerate(range(de, a + 1)):
        n = max(1, marches - k)
        g = gammes[m - 1]
        for i in range(n):
            s.note(piste, g[i], s.m(m) + 0.5 * i, 0.5, vel=vel + (12 if i == 0 else 0))


