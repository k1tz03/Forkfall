# --- F3 : la tonalité (fenêtre) ----------------------------------------------------------------------------
@theme.section('F3', mesures=8)
def F3(s):
    nuances(s, air='p', halo='p', flute='mp', basses_tenu='p', choeur='pp')
    s.note(timbales, 'G2', 0, 1, vel=72)            # le premier temps marqué (on peut reprendre ici)
    # un la tenu : la mèche de do♯, et le la de la tonalité d'un téléphone ; dessous, sol–ré au
    # chœur, très loin : la neuvième ne se résout pas
    s.joue(halo, tenue(['A4'], 28, vel=64))
    s.note(air, 'A5', 0, 28, vel=62)
    s.note(flute, 'A4', s.m(1, 2), 24, vel=72)      # la flûte sans vibrato : le son le plus pur
    s.expression(flute, [(s.m(1, 2), 'p'), (s.m(4), 'mp'), (s.m(7, 4), 'p')])
    s.joue(choeur, tenue(['G3', 'D4'], 28, vel=58))
    s.expression(choeur, [(0, 'pp'), (s.m(5), 'p'), (s.m(8), 'pp')])
    s.note(basses_tenu, 'G2', 0, 16, vel=62)
    # la relance : un roulement sur sol qui enfle jusqu'au premier temps de A1, une cymbale qui
    # monte, le fixe, la basse qui remonte (la couture : la dernière mesure doit déjà sonner
    # comme la première)
    roulement(s, timb_roul, 'G2', s.m(7, 3), s.m(9), 'pp', 'f', vel=84)
    cymbale_vers(s, s.m(9), 'monte_2s', vel=88)
    fixe(s, 8, fois=2, vel=82, pizz=True)
    s.note(basse, 'D2', s.m(8, 3), 1, vel=98)
    s.note(basse, 'G1', s.m(8, 4), 1, vel=106)
    s.note(celles, 'D3', s.m(8, 3), 0.5, vel=84)
    s.note(celles, 'G2', s.m(8, 4), 0.5, vel=90)


