def grille(mesures):
    """Une grille d'accords par mesure (un nom, ou une cellule de CELLULES) → temps par temps."""
    sortie = []
    for c in mesures:
        sortie += CELLULES.get(c, [c] * 4)
    return sortie


def plages(temps):
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def voicing(ch, grave):
    """Les sons de l'accord nommé, chacun au plus près au-dessus de `grave`."""
    g = hauteur(grave)
    sortie = set()
    for h in accord_nomme(ch, octave=2):
        while h < g:
            h += 12
        sortie.add(h)
    return sorted(sortie)


def nappe(s, piste, temps, grave, vel=70, art=None, de=0, jusqua=None):
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        for h in voicing(c, grave):
            s.note(piste, h, a, min(d + l, fin) - a, vel=vel, art=art)


# La basse lourde : croches 3+3+2 (le 3+3+2 du thème principal), deux figures qui alternent ;
# chaque coup est une note (les trois premiers coups tiennent, le dernier est bref) ; les
# contrebasses (pizzicato) et les violoncelles (spiccato) frappent avec elle, une octave dessus.
COUPS = (((0.0, 1.4), (1.5, 1.4), (3.0, 0.9)),            # 1, 2 et, 4
         ((0.0, 1.4), (1.5, 0.9), (2.5, 0.4), (3.0, 0.9)))  # 1, 2 et, 3 et, 4 (la relance)


def basse_lourde(s, temps, de=1, a=None, vel=100, cordes=True, figures=(0, 0, 0, 1), octaves=False,
                 lie=()):
    """La basse lourde des mesures `de` à `a` (comprises) sur la fondamentale de chaque coup ;
    `octaves` : le dernier coup à l'octave ; `lie` : les mesures dont le dernier coup glisse
    vers la fondamentale de la mesure suivante (le triton qui tombe)."""
    a = a or s.mesures
    for m in range(de, a + 1):
        fig = COUPS[figures[(m - de) % len(figures)]]
        for k, (dt, d) in enumerate(fig):
            t = s.m(m) + dt
            c = temps[int(t)]
            h = hauteur(BASSE[c])
            if octaves and k == len(fig) - 1:
                h += 12
            v = vel + (10 if k == 0 else 0)
            if m in lie and k == len(fig) - 1 and m < s.mesures:
                # le dernier coup tient jusqu'à la mesure suivante : la note suivante y glisse
                s.note(basse, h, t, 1.0, vel=v)
            else:
                s.note(basse, h, t, d, vel=v)
            if cordes:
                s.note(basses, h + 12 if h < hauteur('E2') else h, t, 0.5, vel=v - 8)
                s.note(celles, h + 12 if h < hauteur('C3') else h, t, 0.5, vel=v - 14)


def fixe(s, mesure, fois=2, vel=88, pizz=True, depuis=0):
    """Le fixe sonne : sol4 → ré5 sur les contretemps de croche (0,5 et 1,5 ; 2,5 et 3,5) ;
    `depuis` 1 : seulement la seconde moitié de la mesure."""
    for k in range(depuis, fois):
        b = s.m(mesure) + 2 * k
        for dt, h in ((0.5, 'G4'), (1.5, 'D5')):
            s.note(fixe_vib, h, b + dt, 0.5, vel=vel - 6 * k)
            s.note(fixe_mar, h, b + dt, 0.5, vel=vel - 4 - 6 * k)
            if pizz:
                s.note(fixe_pizz, h, b + dt, 0.5, vel=vel - 10 - 6 * k)


def clapet(s, mesure, fois=2, vel=88, pizz=True, neveu=False, depuis=0):
    """Le clapet sonne : sol♯5 → do♯6 sur les contretemps de double croche (0,75 et 1,25 ;
    2,75 et 3,25) ; `depuis` 1 : seulement la seconde moitié de la mesure."""
    for k in range(depuis, fois):
        b = s.m(mesure) + 2 * k
        for dt, h in ((0.75, 'G#5'), (1.25, 'C#6')):
            s.note(clapet_glock, h, b + dt, 0.25, vel=vel - 6 * k)
            if pizz:
                s.note(clapet_pizz, hauteur(h) - 12, b + dt, 0.25, vel=vel - 8 - 6 * k)
            if neveu:
                s.note(clapet_xylo, hauteur(h) - 12, b + dt, 0.25, vel=vel - 4 - 6 * k)


def truelle_coup(s, t, vel=80):
    """La truelle sur la brique : le cercle de la caisse claire et un grattement."""
    s.note(cercle, 'C4', t, 0.25, vel=vel)
    s.note(truelle, 'C5', t + 0.02, 0.3, vel=vel - 6)


def cymbale_vers(s, fin, art='monte_4s', vel=90):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * SEC, secondes * SEC, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=84):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def timbale(c):
    """La timbale de chaque accord (sol2, do♯3, mib2, fa2, la2, si2)."""
    return {'Gm': 'G2', 'C#m': 'C#3', 'Eb': 'Eb2', 'F': 'F2', 'F5': 'F2', 'A': 'A2', 'B': 'B2',
            'B5': 'B2'}[c]


