@theme.section('intro', mesures=4)
def intro(s):
    t = par_temps(['Bs2', 'Bs2', 'A/B', 'Bs2'])
    nuances(s, contrebasses='pp', piano='mp', pizz='p', balais='p', altos='pp', violons2='pp', nappe='p')
    # l'arc, sans impact : il devient le bip du répondeur (la même note)
    arc.poser(s, 0, impact=False, vel=116)
    le_bip(s, 1.0)
    s.note(contrebasses, 'B1', 0, 16, vel=60)
    s.crescendo(contrebasses, 0, 16, 'pp', 'p')
    s.note(nappe, 'F#3', s.m(2), 12, vel=60)
    s.note(nappe, 'C#4', s.m(2), 12, vel=56)
    # la voiture qui ne démarre pas : « fu-si »… « fu-si »…
    s.joue(piano, FU_SI, a=s.m(2, 4), vel=58)
    s.joue(piano, FU_SI, a=s.m(3, 4), vel=54)
    s.joue(piano, FU_SI, a=s.m(4, 4), vel=60)
