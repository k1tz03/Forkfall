def par_temps(grille):
    """Une grille d'accords → un accord par temps (une entrée peut être une liste de quatre)."""
    sortie = []
    for c in grille:
        sortie += list(c) if isinstance(c, (list, tuple)) else [c] * 4
    return sortie


def plages(temps):
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def nappe_cordes(s, temps, pistes, vel=64, de=0, jusqua=None, octave=0):
    """Les voix de chaque accord, partagées entre les pistes (de la plus grave à la plus aiguë),
    tenues de `de` à `jusqua`."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        voix = [hauteur(h) + 12 * octave for h in ACC[c][1]]
        for k, h in enumerate(voix):
            s.note(pistes[min(len(pistes) - 1, k * len(pistes) // len(voix))], h, a, min(d + l, fin) - a, vel=vel)


def basse(s, piste, temps, vel=70, de=0, jusqua=None, art=None):
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        s.note(piste, ACC[c][0], a, min(d + l, fin) - a, vel=vel, art=art)


def essuie_glaces(s, de, a, vel=72, chaque_temps=False, balancier=None, temps=None, vel_b=66):
    """Les essuie-glaces, de la mesure `de` à `a` comprises : le frottement du balai à l'aller (le 1)
    et au retour (le 3), un petit coup en bout de course (le 2 et le 4) ; `chaque_temps` : la pluie
    forcit, un frottement à chaque temps. `balancier` : la piste qui joue les deux notes du bras."""
    for m in range(de, a + 1):
        if chaque_temps:
            s.joue(balais, batterie('S2 : x . . . x . . . x . . . x . . .\n'
                                    'S  : . . . o . . . o . . . o . . . o', vel=vel), a=s.m(m))
        else:
            s.joue(balais, batterie('S2 : x . . . . . . . x . . . . . . .\n'
                                    'S  : . . . . g . . . . . . . g . . .', vel=vel), a=s.m(m))
        if balancier is not None:
            for b in (0, 2) if not chaque_temps else (0, 1, 2, 3):
                c = temps[(m - 1) * 4 + b]
                h1, h2 = BALANCIER[c]
                s.note(balancier, h1 if b % 2 == 0 else h2, s.m(m, b + 1), 1, vel=vel_b)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=90):
    """Un roulement qui enfle de `de` à `a` (en temps)."""
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def le_bip(s, a, duree=0.62, vel=100):
    """Le bip du répondeur (si5), un peu plus d'une demi-seconde."""
    s.note(bip, 'B5', a, duree * SEC, vel=vel)


def la_bande(s, a, vel=92):
    """La bande qui rembobine : le motif à l'envers, huit fois plus vite, deux octaves au-dessus,
    puis le déclic."""
    s.joue(bande, RETRO.diminue(8).octave(2), a=a, vel=vel + 12)
    s.note(clic, 'SR', a + 1.15, 0.25, vel=96)


def les_pieces(s, a, vel=80):
    """Des pièces qui tombent dans la cabine : la chute du motif (ré do# mi si), en rebonds."""
    for dt, h, v in ((0.0, 'D6', vel), (0.42, 'C#6', vel - 6), (0.66, 'E6', vel - 10), (0.88, 'B5', vel - 4),
                     (1.02, 'B5', vel - 26)):
        s.note(glock, h, a + dt, 0.5, vel=v)


