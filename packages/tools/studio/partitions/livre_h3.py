def enchaine(motif, pas=0.5):
    """La chaîne : chaque note du motif répétée à chaque `pas` (une croche) tant qu'elle dure ;
    un silence prolonge la note d'avant (la machine ne s'arrête pas)."""
    notes = sorted(motif.notes, key=lambda n: n.t)
    sortie = []
    for i, n in enumerate(notes):
        fin = notes[i + 1].t if i + 1 < len(notes) else motif.longueur
        t = n.t
        while t < fin - 1e-9:
            sortie.append(Note(n.h, t, pas, n.v, 'staccato'))
            t += pas
    return Motif(sortie, motif.longueur)


# la chaîne tournée : le do sur la barre, « mi si » à la fin du cycle (deux mesures, 16 croches)
