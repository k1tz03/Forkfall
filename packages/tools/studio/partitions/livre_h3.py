GRILLE_B = ['i', 'i', 'bII', 'i', 'bVI', 'bII', 'i', 'i', 'bVI', 'bvii', 'bII', 'i', 'bVI', 'bII', 'i', 'i']
RAC = {'i': 'E2', 'bII': 'F2', 'bVI': 'C2', 'bvii': 'D2', 'bVII': 'D2', 'iv': 'A2'}


def basse_galop(s, piste, grille_m, de=1, a=None, vel=86, art='staccato', derniere=8, octave=0):
    """La basse en croches sur les fondamentales, l'octave sur les accents 3+3+2 (+0 +0 +12 …)."""
    a = a or len(grille_m)
    for m in range(de, a + 1):
        r = hauteur(RAC[grille_m[m - 1]]) + 12 * octave
        nb = derniere if m == a else 8
        for i, (d, c) in enumerate(zip([0, 0, 12, 0, 0, 12, 0, 7], 'X x x X x x X x'.split())):
            if i >= nb:
                break
            s.note(piste, r + d, s.m(m) + i * 0.5, 0.5, vel=vel + ACC[c] // 2, art=art)


