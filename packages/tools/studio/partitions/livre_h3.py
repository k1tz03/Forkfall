def _temps_par_seconde(s):
    b = s.section.bpm or s.theme.bpm
    if isinstance(b, (tuple, list)):
        b = b[0]
    return b / 60.0


def glisse(s, piste, h0, h1, t0, duree, forme='sirene', pas=0.25, vel=(80, 100), art='legato'):
    """Un glissando de cordes : des micro-pas de `pas` demi-ton (un quart de ton), en legato, de
    `h0` à `h1`, de `t0` pendant `duree` temps ; `forme` 'sirene' : la courbe d'une sirène (vite
    d'abord, puis elle approche sa note, comme le synthé qui glisse), 'lineaire' : régulière.
    Rend l'instant d'arrivée."""
    h0, h1 = hauteur(h0), hauteur(h1)
    n = max(2, int(round(abs(h1 - h0) / pas)))
    q = 1 - math.exp(-3.0)

    def instant(p):
        if forme == 'lineaire':
            return p
        return -math.log(1 - p * q) / 3.0

    for k in range(n):
        p0, p1 = k / n, (k + 1) / n
        a, b = t0 + duree * instant(p0), t0 + duree * instant(p1)
        v = vel[0] + (vel[1] - vel[0]) * p0
        s.note(piste, h0 + (h1 - h0) * p0, a, max(0.02, b - a), vel=v, art=art)
    return t0 + duree


def sirene(s, a, tenue=6, apres=3, montee=4, depart=2, chute=3, cordes=True, cor=True, choeur_art=None,
           vel=96, synthe=True, mourir=False, cor_apres=None, fort='f', premiers=True):
    """La sirène à la position `a` (en temps) : le synthé part de mi2 (très bas, `depart` temps),
    monte en `montee` temps jusqu'au do (la mèche), le tient `tenue` temps, retombe en `chute` temps
    sur si et le tient `apres` temps ; les cordes glissent avec lui (violons de mi4, seconds de sol3,
    altos de mi3 à do4), le cor tient la mèche, le chœur (`choeur_art`) s'y joint. `mourir` : le
    synthé, au lieu de tenir si, retombe encore et s'éteint (le moteur qui s'arrête) ; `fort` : la
    nuance des cordes et du chœur sur la mèche (une sirène lointaine : 'mp') ; `premiers` : les
    premiers violons avec elles (sans eux, les seconds tiennent seuls le haut : la sirène est loin)."""
    sec = _temps_par_seconde(s)
    g = 2.0 * sec                                  # la glissade du synthé, en temps
    haut = a + depart                              # le début de la montée
    arrivee = haut + montee                        # la mèche
    fin_tenue = arrivee + tenue
    fin = fin_tenue + chute + apres
    if synthe:
        s.note(sirene_s, MI2, a, depart, vel=vel - 20)
        s.note(sirene_s, DO5, haut, arrivee + tenue - haut, vel=vel, glisse=True)
        if mourir:
            s.note(sirene_s, SI4, fin_tenue, chute + 1, vel=vel - 4, glisse=True)
            s.note(sirene_s, T.degre(1, 3), fin_tenue + chute + 1, max(1.0, apres - 1), vel=vel - 30,
                   glisse=True)
            s.expression(sirene_s, [(a, 'p'), (arrivee, 'f'), (fin_tenue + chute, 'f'), (fin, 'ppp')])
        else:
            s.note(sirene_s, SI4, fin_tenue, chute + apres, vel=vel - 4, glisse=True)
            s.expression(sirene_s, [(a, 'p'), (arrivee, 'f'), (fin - 1, 'f'), (fin, 'mp')])
    if cordes:
        # les cordes entrent pendant la montée, là où la courbe du synthé passe par leur note
        for piste, h0, h_haut, h_bas, entre in ((violons, 'E4', DO5, SI4, 0.45), (violons2, 'G3', DO5, SI4, 0.25),
                                                (altos, 'E3', DO5 - 12, SI4 - 12, 0.25)):
            if piste is violons and not premiers:
                continue
            t_in = haut + montee * entre
            glisse(s, piste, h0, h_haut, t_in, arrivee - t_in, vel=(vel - 30, vel))
            s.note(piste, h_haut, arrivee, tenue, vel=vel + 2, art='legato')
            glisse(s, piste, h_haut, h_bas, fin_tenue, chute, vel=(vel, vel - 4))
            s.note(piste, h_bas, fin_tenue + chute, apres, vel=vel - 4, art='legato')
            s.expression(piste, [(t_in, 'p'), (arrivee, fort), (fin_tenue, fort),
                                 (fin, 'mf' if fort == 'f' else 'p')])
    if cor:
        # le cor chante la tête dans la sirène : « fu-si » juste avant qu'elle arrive, « BLE » avec
        # elle sur la mèche ; puis il retombe avec elle sur la quinte
        s.joue(cors, ANACROUSE.octave(1), a=arrivee - 1, vel=vel + 2)
        s.note(cors, DO5, arrivee, tenue, vel=vel + 4)
        s.note(cors, SI4, fin_tenue + chute * 0.5, chute * 0.5 + (apres if cor_apres is None else cor_apres),
               vel=vel)
    if choeur_art:
        s.note(choeur, DO5 - 12, arrivee, tenue, vel=vel, art=choeur_art)
        s.note(choeur, SI4 - 12, fin_tenue + chute * 0.5, chute * 0.5 + apres, vel=vel - 6, art=choeur_art)
        s.expression(choeur, [(arrivee, 'mp'), (fin_tenue, fort), (fin, 'mf' if fort == 'f' else 'p')])
    return fin


def sans_fin(s, de, a, periode=16.0, bas='E3', octaves=3, vel=84, pas=0.25):
    """La sirène qui monte sans fin (le pont) : trois voix d'altos, à l'octave l'une de l'autre,
    glissent ensemble vers le haut, une octave par `periode` temps ; chacune enfle au milieu et
    s'éteint aux deux bouts (une cloche sur la hauteur) : la plus aiguë disparaît pendant que la
    plus grave entre, et ça monte toujours."""
    h_bas = hauteur(bas)
    etendue = 12 * octaves
    centre = h_bas + etendue / 2.0
    largeur = etendue / 4.0
    duree_pas = periode * pas / 12.0
    for k, piste in enumerate(nuit):
        t = de
        h = h_bas + 12 * k                       # les voix partent décalées d'une octave
        while t < a - 1e-9:
            poids = math.exp(-((h - centre) / largeur) ** 2)
            v = max(1, int(vel * poids))
            s.note(piste, h, t, duree_pas, vel=v, art='legato')
            t += duree_pas
            h += pas
            if h >= h_bas + etendue:
                h -= etendue


# --- les percussions ---------------------------------------------------------------------------
def la_presse(s, de, a, motifs=('K : X . . . . . . . X . . . . . . .',
                               'K : X . . . . . x . X . . . . . . .'), vel=104, double=True):
    """La presse : la grosse caisse de la boîte sur 1 et 3 (et une croche avant le 3 une mesure
    sur deux), doublée sur le 1 par la grosse caisse d'orchestre."""
    for m in range(de, a + 1):
        s.batterie(presse, motifs[(m - de) % len(motifs)], a=s.m(m), jusqua=s.m(m + 1), vel=vel)
        if double:
            s.note(gcaisse, 'C4', s.m(m), 1, vel=vel - 24)


def la_caisse(s, de, a, vel=96, fin=None):
    """La caisse « gated » de la boîte sur 2 et 4, la caisse claire d'orchestre dessous."""
    for m in range(de, a + 1):
        for b in (2, 4):
            t = s.m(m, b)
            if fin is not None and t >= fin:
                continue
            s.note(claque, 'S', t, 0.5, vel=vel)
            s.note(caisse, 'S', t, 0.5, vel=vel - 30)


def le_marteau(s, de, a, vel=84, places=((1, 2.5), (2, 4.0))):
    """Le marteau (l'enclume) : une frappe aux accents, sur un cycle de deux mesures."""
    for m in range(de, a + 1):
        for k, b in places:
            if (m - de) % 2 == k - 1:
                s.note(marteau, 'C4', s.m(m, b), 0.5, vel=vel)


def cymbale_vers(s, fin, art='monte_4s', vel=90):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    sec = _temps_par_seconde(s)
    s.note(suspendue, 'C4', fin - secondes * sec, secondes * sec, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=88):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


# le fil de la tréfileuse (B) : des doubles croches sur l'accord, le voisin du dessus qui frotte ;
# les figures en pas de gamme depuis la fondamentale, groupées 3+3+2
FIL = [[0, 1, 0, -3], [2, 1, 0, 4], [0, 4, 2, 4], [4, 5, 4, 2], [7, 4, 5, 4]]


def le_fil(s, piste, de, a, racines, vel=76, derniere=16):
    """Le fil : chaque temps quatre doubles croches sur sa fondamentale (`racines` : une note par
    mesure), une figure par temps en rotation, jamais deux mesures pareilles ; accents 3+3+2."""
    acc = 'X x o X x o X x X x o X x o X o'.split()
    for m in range(de, a + 1):
        r = hauteur(racines[(m - de) % len(racines)])
        nb = derniere if m == a else 16
        for i in range(nb):
            fig = FIL[((m - de) + i // 4) % len(FIL)]
            h = T.pas_diatonique(r, fig[i % 4])
            s.note(piste, h, s.m(m) + i * 0.25, 0.25, vel=vel + ACC[acc[i]] // 2, art='staccato')


