@theme.section('A', mesures=16)
def A(s):
    nuances(s, celles='mp', basse='mp', basses='mp', guitare='mf', altos='mp', vibra='mp', harpe='mf')
    grille = ROUTE * 4
    s.note(cymbales, 'C4', 0, 2, vel=58)
    # le moteur : la pédale de fa#, des croches
    moteur(s, celles, 1, 16, 'F#2', vel=78)
    moteur(s, basse, 1, 16, 'F#1', vel=74, art=None, rot=2)
    for m in range(1, 17):
        s.note(basses, 'F#1', s.m(m), 1, vel=88, art='pizzicato')
    s.note(sub, 'F#1', 0, s.longueur, vel=56)
    # les lampadaires : la harpe seule, puis l'arpège de synthé avec elle (m. 9)
    lampadaires(s, 1, 8, grille, vel=80, synthe=False)
    lampadaires(s, 9, 16, grille, vel=80)
    # le paysage : les accords tenus, très bas (les altos, puis les seconds violons à la m. 5)
    nappe_grille(s, altos, 1, 16, grille, 'C#4', vel=56)
    nappe_grille(s, violons2, 5, 16, grille, 'A4', vel=56)
    s.crescendo(violons2, s.m(5), s.m(9), 'p', 'mp')
    # la boîte : le cercle (m. 1-4), puis la caisse ; le charleston à la m. 9
    la_route(s, 1, 16, caisse_des=5, charleston_des=9)
    # la route s'ouvre : le moteur et la boîte partent doux et grandissent jusqu'au motif
    s.expression(celles, [(0, 'p'), (s.m(10), 'mf')])
    s.expression(kick, [(0, 'p'), (s.m(9), 'f')])
    s.expression(boite, [(0, 'p'), (s.m(9), 'f')])
    # la guitare : un accord en trémolo à chaque mesure (m. 1-9 ; ♭VII en quinte à vide, plus doux),
    # puis le motif en valeurs longues
    for m in range(1, 10):
        for h in voicing(grille[m - 1], 'F#3'):
            s.note(guitare, h, s.m(m), 4, vel=78 if m % 2 else 68)
    s.expression(guitare, [(0, 'p'), (s.m(2), 'mp')])
    tremolo(s, guitare, 0, s.longueur, prof=-8.0)
    # m. 10 : le motif, la guitare devant les lampadaires
    s.joue(guitare_chant, LENT, a=s.m(10, 3), vel=98)
    s.joue(guitare_chant, TETE_LENTE, a=s.m(14, 3), vel=94)
    devant(s, s.m(10, 3), s.m(16))
    # le vibraphone double l'attaque des notes longues, de loin
    s.joue(vibra, LENT.coupe(0, 10), a=s.m(10, 3), vel=66)
    cymbale_vers(s, s.m(17), 'monte_2s', vel=78)


