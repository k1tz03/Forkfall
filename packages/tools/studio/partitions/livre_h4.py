def basse_galop(s, piste, grille_m, de=1, a=None, vel=84, art='staccato', derniere=8, octave=2):
    """La basse au galop : des croches sur les fondamentales, l'octave sur les accents 3+3+2."""
    a = a or len(grille_m)
    for m in range(de, a + 1):
        r = racine(grille_m[m - 1], octave)
        if r < hauteur('E1'):
            r += 12
        nb = derniere if m == a else 8
        for i, (d, c) in enumerate(zip([0, 0, 12, 0, 0, 12, 0, 7], 'X x x X x x X x'.split())):
            if i >= nb:
                break
            s.note(piste, r + d, s.m(m) + i * 0.5, 0.5, vel=vel + ACC[c] // 2, art=art)


