@theme.section('intro', mesures=4)
def intro(s):
    """Le contact : l'arc, le moteur qui s'allume, les premiers lampadaires, la tête à la guitare."""
    nuances(s, celles='p', basse='p', guitare='mf', violons2='pp', altos='pp', basses='p')
    arc.poser(s, 0, impact=True, vel=118)
    # le moteur s'allume après l'arc (m. 1, 3e temps), pianissimo, et monte
    for i in range(4):
        s.note(celles, 'F#2', s.m(1, 3) + i * 0.5, 0.5, vel=60 + 4 * i, art='staccato')
    moteur(s, celles, 2, 4, 'F#2', vel=72)
    s.expression(celles, [(0, 'pp'), (s.m(4, 4), 'mp')])
    moteur(s, basse, 2, 4, 'F#1', vel=70, art=None)
    s.note(basses, 'F#1', s.m(1, 3), 14, vel=64, art='tenu')
    # les premiers lampadaires (m. 2)
    lampadaires(s, 2, 4, ['i', 'bVI', 'bVII'], vel=76)
    # la guitare : la tête en valeurs longues (fa# do# | ré), son trémolo ; « la tête à 3,5 s »
    s.joue(guitare, TETE_LENTE, a=s.m(2, 3), vel=96)
    tremolo(s, guitare, 0, s.longueur, prof=-9.0)
    nappe_grille(s, altos, 3, 4, ['bVI', 'bVII'], 'D4', vel=58)
    s.crescendo(altos, s.m(3), s.m(4, 4), 'pp', 'p')
    cymbale_vers(s, s.m(5), 'monte_4s', vel=80)


