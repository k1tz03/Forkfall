RACINES = {'i': 'F#', 'bVII': 'E', 'bVI': 'D', 'bII': 'G', 'IV': 'B', 'iv': 'B', 'v': 'C#', 'I': 'A',
           'V': 'E', 'vi': 'F#', 'IVr': 'D'}
ROUTE = ['i', 'bVII', 'bVI', 'bVII']


def racine(ch, octave):
    h = hauteur(f'{RACINES[ch]}{octave}')
    return h


def voicing(ch, grave, ton=TON):
    """Les sons de l'accord, chacun au plus près au-dessus de `grave`. ♭VII sonne en quinte à vide
    (mi–si) : sous « la sol# » du motif, la quarte suspendue et sa résolution sonnent toutes deux
    justes (l'habitude du thème principal)."""
    if ch == 'bVII':
        ch = 'bVII5'
    g = hauteur(grave)
    sortie = set()
    for h in accord(ch, ton, octave=2):
        while h < g:
            h += 12
        sortie.add(h)
    return sorted(sortie)


def tremolo(s, piste, de, a, pas=0.25, prof=-9.0):
    """Le trémolo d'ampli : le volume de la piste bat à chaque `pas` (une double croche), de 0 à
    `prof` dB, de `de` à `a` (en temps)."""
    pts = []
    t = de
    while t < a - 1e-9:
        pts.append((t, 0.0))
        pts.append((t + pas / 2, prof))
        t += pas
    pts.append((a, 0.0))
    s.automation(piste, 'volume', pts)


def devant(s, de, fin, harpe_normale='mf'):
    """Pendant que la guitare chante le motif (de `de` à `fin`, en temps), elle passe devant : sa
    voix claire (`guitare_chant`), nuance f, un trémolo moins profond (−4 dB au lieu de −8) ; les
    lampadaires (la harpe, l'arpège) s'effacent sous elle (p), puis reprennent leur place."""
    s.nuance(guitare_chant, 'f', de)
    tremolo(s, guitare_chant, de, fin, prof=-4.0)
    s.expression(harpe, [(de - 1, harpe_normale), (de, 'p'), (fin - 1, 'p'), (fin, harpe_normale)])
    s.expression(arp, [(de - 1, 'fff'), (de, 'p'), (fin - 1, 'p'), (fin, 'fff')])


# le moteur : des croches sur une note (la pédale), l'octave qui bouge un peu, jamais deux
# mesures pareilles à la suite
MOTEUR = [([0, 0, 0, 0, 0, 0, 0, 0], 'X o x o X o x o'), ([0, 0, 0, 12, 0, 0, 0, 0], 'X o x o X o x o'),
          ([0, 0, 0, 0, 0, 0, 12, 0], 'X o x o X o x x'), ([0, 0, 12, 0, 0, 0, 0, 7], 'X o x o X o x o')]
ACC = {'X': 16, 'x': 0, 'o': -14}


def moteur(s, piste, de, a, notes, vel=78, art='staccato', derniere=8, rot=0):
    """Le moteur en croches de la mesure `de` à `a` ; `notes` : une hauteur (la pédale) ou une
    liste, une par mesure (les fondamentales)."""
    for m in range(de, a + 1):
        h = hauteur(notes if isinstance(notes, str) else notes[(m - de) % len(notes)])
        dec, acc = MOTEUR[(m - de + rot) % len(MOTEUR)]
        acc = acc.split()
        nb = derniere if m == a else 8
        for i in range(nb):
            s.note(piste, h + dec[i], s.m(m) + i * 0.5, 0.5, vel=vel + ACC[acc[i]], art=art)


# les lampadaires : l'arpège de l'accord, une note par noire (ou par double croche dans B)
LAMPES = ['1 2 3 4', '2 3 4 3', '3 4 2 3', '1 3 2 4']


def lampadaires(s, de, a, grille_m, pas=1.0, vel=84, grave='C#4', motifs=LAMPES, synthe=True, ton=TON):
    for m in range(de, a + 1):
        ch = grille_m[(m - de) % len(grille_m)]
        v = voicing(ch, grave, ton)
        mot = motifs[(m - de) % len(motifs)]
        if pas < 1.0:
            mot = ' '.join([mot] * int(round(1.0 / pas)))
        s.joue(harpe, arpege(v, mot, pas=pas, vel=vel), a=s.m(m))
        if synthe:
            s.joue(arp, arpege(v, mot, pas=pas, vel=vel - 10), a=s.m(m))


def nappe_grille(s, piste, de, a, grille_m, grave, vel=60, art=None, ton=TON, jusqua=None):
    for m in range(de, a + 1):
        ch = grille_m[(m - de) % len(grille_m)]
        fin = s.tpm if jusqua is None or m < a else jusqua
        for h in voicing(ch, grave, ton):
            s.note(piste, h, s.m(m), fin, vel=vel, art=art)


def la_route(s, de, a, caisse_des=5, vel=96, charleston_des=None, fin=None):
    """La boîte à rythmes de la route : grosse caisse sur 1, 2 et demi, 3 ; le cercle puis la
    caisse sur 2 et 4 ; le charleston en croches, très doux ; la grosse caisse d'orchestre sur 1."""
    for m in range(de, a + 1):
        piece = 'S' if m >= caisse_des else 'SR'
        jusqua = min(s.m(m + 1), fin) if fin is not None else s.m(m + 1)
        motif = f'{piece} : . . . . X . . . . . . . X . . .'
        if charleston_des is not None and m >= charleston_des:
            motif += '\nH : x . o . x . o . x . o . x . o .'
        s.batterie(kick, 'K : X . . . . . x . X . . . . . . .', a=s.m(m), jusqua=jusqua, vel=vel)
        s.batterie(boite, motif, a=s.m(m), jusqua=jusqua, vel=vel)
        s.note(gcaisse, 'C4', s.m(m), 1, vel=vel - 30)


def cymbale_vers(s, fin, art='monte_4s', vel=88):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * 104 / 60.0, secondes * 104 / 60.0, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=88):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


