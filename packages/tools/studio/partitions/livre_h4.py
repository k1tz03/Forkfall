    for p in (violons2, altos, celles_chant):
        s.crescendo(p, 0, s.m(4, 4), 'pp', 'p')
    # la guitare : un seul accord, sous sa réponse (m. 7)
    for h in voicing(GRILLE_CL[6], 'F#3', DOR):
        s.note(guitare, h, s.m(7), 4, vel=72)
    # LE SIFFLET : la montée en dorien, qui atteint l'octave sur fa# mineur (m. 4-6)
    s.joue(sifflet, SIFFLE, a=s.m(4, 4), vel=100)
    s.nuance(sifflet, 'mf', s.m(4, 4))
    # la guitare répond en dorien (m. 7-8) : la tête, ré# tenu
    s.joue(guitare, TETE_DOR, a=s.m(7, 3) - 2, vel=90)
    tremolo(s, guitare, 0, s.longueur, prof=-10.0)
    # m. 9 : le moteur repart ; les lampadaires reviennent ; la boîte
    moteur(s, celles, 9, 12, 'F#2', vel=74)
    s.crescendo(celles, s.m(9), s.m(12, 4), 'pp', 'mp')
    moteur(s, basse, 11, 12, 'F#1', vel=70, art=None)
    lampadaires(s, 9, 12, ['i', 'IV', 'bVII', 'bVII'], vel=72, ton=DOR)
    for m in (11, 12):
        s.batterie(kick, 'K : X . . . . . . . X . . . . . . .', a=s.m(m), jusqua=s.m(m + 1), vel=90)
        s.batterie(boite, 'SR : . . . . X . . . . . . . X . . .', a=s.m(m), jusqua=s.m(m + 1), vel=90)
    s.note(basses, 'F#1', s.m(9), 16, vel=60, art='tenu')
    # le premier temps marqué, doux (une timbale, un accord de harpe, la contrebasse) : la section
    # ouvre à froid, et la fenêtre presque vide commence sur ce souffle
    s.note(timbales, 'F#2', 0, 1, vel=84)
    for h in voicing('i', 'F#3', DOR):
        s.note(harpe, h, 0, 2, vel=84)
    s.expression(harpe, [(0, 'mf'), (s.m(1, 3), 'p')])
    s.note(basses, 'F#1', 0, 4, vel=64, art='tenu')
    s.expression(basses, [(0, 'p'), (s.m(2), 'pp')])
    cymbale_vers(s, s.m(13), 'monte_2s', vel=76)


