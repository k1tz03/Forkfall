# la chanson de la radio : fa#m – mi – ré – LA (la même route, qui finissait en majeur)
GRILLE_RADIO = ['vi', 'V', 'IVr', 'I']
RADIO_TON = 'la majeur'


@theme.section('C', mesures=16)
def C(s):
    nuances(s, celles='p', basses='mp', harpe='p', radio_lead='f', radio_vibra='f', radio_boite='f',
            radio_basse='f', radio_mains='f', violons2='pp', altos='pp')
    # la radio qu'on allume : l'arc (sans son coup grave), dans le silence de la fin de A2
    arc.poser(s, 0, impact=False, vel=112)
    # rien ne sort de la radio : ses pistes n'envoient rien aux salles (pas même la pièce de la
    # batterie), tout passe par la bande du poste
    for p in RADIO:
        s.automation(p, 'envoi', [(0, 0.0), (s.longueur, 0.0)])
    grille = GRILLE_RADIO * 3
    # la chanson : le motif à l'envers, en valeurs longues (m. 1-4, 5-8), puis une octave plus
    # haut avec le vibraphone en sixtes dessous (m. 9-12)
    for k in range(2):
        s.joue(radio_lead, RETRO, a=s.m(1 + 4 * k), vel=96)
        s.joue(radio_vibra, RETRO, a=s.m(1 + 4 * k), vel=92)
    s.joue(radio_lead, RETRO.octave(1), a=s.m(9), vel=100)
    s.joue(radio_vibra, RETRO.octave(1).diatonique(-5, RADIO_TON), a=s.m(9), vel=88)
    # la basse en octaves, la boîte, les mains de la fête (2 et 4)
    for m in range(1, 13):
        r = hauteur(f'{RACINES[grille[m - 1]]}2')
        s.joue(radio_basse, seq(' '.join([f'{nom(r)} {nom(r + 12)}'] * 4), pas=0.5, vel=90), a=s.m(m))
        s.batterie(radio_boite, 'K : X . . . . . x . X . . . . . . .\nS : . . . . X . . . . . . . X . . .\n'
                                'H : x . x . x . x . x . x . x . x .', a=s.m(m), jusqua=s.m(m + 1), vel=96)
        s.batterie(radio_mains, 'CL : . . . . X . . . . . . . X . . .', a=s.m(m), jusqua=s.m(m + 1), vel=96)
    # m. 13-14 : la radio s'éteint (sa chanson continue, de plus en plus loin)
    s.joue(radio_lead, RETRO.coupe(0, 6), a=s.m(13), vel=90)
    for m in (13, 14):
        r = hauteur(f'{RACINES[GRILLE_RADIO[m - 13]]}2')
        s.joue(radio_basse, seq(' '.join([f'{nom(r)} {nom(r + 12)}'] * 4), pas=0.5, vel=86), a=s.m(m))
        s.batterie(radio_boite, 'K : X . . . . . x . X . . . . . . .\nS : . . . . X . . . . . . . X . . .',
                   a=s.m(m), jusqua=s.m(m + 1), vel=90)
    for p in RADIO:
        s.expression(p, [(s.m(13), 'f'), (s.m(15), 0.0)])
    # dehors, la voiture roule : le moteur très doux, les lampadaires lents ; quand la radio
    # s'éteint, tout se tait avec elle (une fenêtre presque vide, la pédale de do# seule)
    moteur(s, celles, 1, 12, 'F#2', vel=70)
    lampadaires(s, 1, 12, ['i', 'bVII', 'bVI', 'bVI'], pas=2.0, vel=66, motifs=['1 3', '2 4', '1 2', '3 2'],
                synthe=False)
    for m in range(1, 13):
        s.note(basses, 'F#1', s.m(m), 1, vel=80, art='pizzicato')
    # m. 13 : le do# qui ramène la nuit (la pédale de dominante, jamais résolue)
    s.note(basses, 'C#2', s.m(13), 16, vel=74, art='tenu')
    s.note(celles_chant, 'C#3', s.m(13), 16, vel=70)
    s.crescendo(basses, s.m(13), s.m(16, 4), 'p', 'mf')
    s.crescendo(celles_chant, s.m(13), s.m(16, 4), 'pp', 'mf')
    for h in ('C#4', 'F#4', 'G#4'):
        s.note(altos, h, s.m(14), 12, vel=62)
    for h in ('G#4', 'C#5'):
        s.note(violons2, h, s.m(15), 8, vel=62)
    s.crescendo(altos, s.m(14), s.m(16, 4), 'pp', 'mp')
    s.note(timbales, 'C#3', s.m(16), 1, vel=80)
    roulement(s, timb_roul, 'C#3', s.m(15), s.m(17), 'pp', 'mf', vel=80)
    cymbale_vers(s, s.m(17), 'monte_4s', vel=86)


