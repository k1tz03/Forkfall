@theme.section('clairiere', mesures=12)
def clairiere(s):
    nuances(s, violons2='p', altos='p', celles_chant='p', guitare='mp', sifflet='mf', harpe='p',
            nappe='p', basses='pp', celles='pp', kick='mf', boite='mf', basse='mp')
    # les mains sur les genoux : plus de moteur ; la nappe, les cordes très douces (dorien)
    for m, c in enumerate(GRILLE_CL, start=1):
        if m == 5:
            for h in voicing('IV', 'D#4', DOR):
                s.note(violons2, h, s.m(5), 2, vel=58)
            for h in voicing('bVII', 'D#4', DOR):
                s.note(violons2, h, s.m(5, 3), 2, vel=58)
            for h in voicing('IV', 'F#3', DOR):
                s.note(altos, h, s.m(5), 2, vel=56)
            for h in voicing('bVII', 'F#3', DOR):
                s.note(altos, h, s.m(5, 3), 2, vel=56)
            s.note(celles_chant, 'B2', s.m(5), 2, vel=58)
            s.note(celles_chant, 'E2', s.m(5, 3), 2, vel=58)
            continue
        for h in voicing(c, 'D#4', DOR):
            s.note(violons2, h, s.m(m), 4, vel=58)
        for h in voicing(c, 'F#3', DOR):
            s.note(altos, h, s.m(m), 4, vel=56)
        s.note(celles_chant, racine(c, 2) if c != 'IV' else hauteur('B2'), s.m(m), 4, vel=58)
        s.note(nappe, racine(c, 3), s.m(m), 4, vel=50)
