def temps_accords(mesures):
    sortie = []
    for c in mesures:
        sortie += CELLULES.get(c, [c] * 4)
    return sortie


def racine(ch, octave, plancher='E1'):
    """La fondamentale de l'accord à l'octave dite, jamais sous `plancher`."""
    pc = fondamentale(ch, TON)[0]
    h = 12 * (octave + 1) + pc
    while h < hauteur(plancher):
        h += 12
    return h


def voicing(ch, grave):
    """Les sons de l'accord, chacun au plus près au-dessus de `grave`."""
    g = hauteur(grave)
    sortie = set()
    for h in accord(ch, TON, octave=2):
        while h < g:
            h += 12
        sortie.add(h)
    return sorted(sortie)


def plages(temps):
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def nappe(s, piste, temps, grave, vel=70, art=None, de=0, jusqua=None):
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d < de or d >= fin:
            continue
        for h in voicing(c, grave):
            s.note(piste, h, d, min(l, fin - d), vel=vel, art=art)


def arpege_temps(s, piste, temps, de, a, table, motif, vel=70, pas=0.5):
    """Un arpège en croches de `de` à `a` (en temps) : chaque note est prise dans l'accord du
    temps où elle tombe (table : chiffre → hauteurs, la première est la basse, laissée de côté)."""
    rangs = motif.split()
    k = 0
    x = de
    while x < a - 1e-9:
        hs = sorted(hauteur(h) for h in table[temps[int(x)]][1:])
        r = int(rangs[k % len(rangs)])
        o, i = divmod(r - 1, len(hs))
        s.note(piste, hs[i] + 12 * o, x, pas, vel=vel)
        k += 1
        x += pas


def oom(s, pistes, temps, de, a, octave=2, vel=92, quinte=True, plancher='E1', duree=1.0):
    """Le « poum » de la marche sur 1 et 3 : la fondamentale, puis (si l'accord ne change pas)
    sa quinte en dessous — la basse fondamentale–quinte, trop grande pour elle."""
    for m in range(de, a + 1):
        for b in (0, 2):
            t = (m - 1) * 4 + b
            ch = temps[t]
            h = racine(ch, octave, plancher)
            if b == 2 and quinte and ch == temps[(m - 1) * 4]:
                h = h - 5 if h - 5 >= hauteur(plancher) else h + 7
            for p in pistes:
                s.note(p, h, t, duree, vel=vel)


def pa(s, pistes, temps, de, a, grave='E3', vel=78, duree=0.5, temps_pa=(1, 3)):
    """Le « pa » de la marche : l'accord sur 2 et 4."""
    for m in range(de, a + 1):
        for b in temps_pa:
            t = (m - 1) * 4 + b
            for h in voicing(temps[t], grave):
                for p in pistes:
                    s.note(p, h, t, duree, vel=vel)


