def marche_caisse(s, piste, de, a, vel=90, motifs=(MARCHE, MARCHE, MARCHE, MARCHE2), relance=True):
    for m in range(de, a + 1):
        txt = RELANCE if (relance and m == a) else motifs[(m - de) % len(motifs)]
        s.batterie(piste, txt, a=s.m(m), jusqua=s.m(m + 1), vel=vel)


def grosse_caisse(s, de, a, vel=96, piste=None):
    for m in range(de, a + 1):
        s.note(piste or gcaisse, 'C4', s.m(m), 1, vel=vel)
        s.note(piste or gcaisse, 'C4', s.m(m, 3), 1, vel=vel - 14)


def chante(s, motif, a, pistes, vel=100):
    """Le même motif sur plusieurs pistes : [(piste, transposition en octaves)]."""
    for p, k in pistes:
        s.joue(p, motif.octave(k), a=a, vel=vel)


def motif_sans_anacrouse(motif):
    """Le motif sans ses deux croches d'appel (une section qui commence sur « BLE »)."""
    return motif.coupe(1, motif.longueur)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=90):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def cymbale_vers(s, fin, art='monte_2s', vel=96):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * SEC, secondes * SEC, vel=vel, art=art)


