NUIT = {'i': ['C3', 'G3', 'D4', 'Eb4', 'G4'], 'bVI': ['Ab2', 'Eb3', 'Bb3', 'C4'],
        'iv': ['F2', 'C3', 'Eb3', 'Ab3', 'C4'], 'V': ['G2', 'D3', 'F3', 'B3'], 'bVII5': ['Bb2', 'F3', 'Bb3'],
        'i5': ['C3', 'G3', 'C4'], 'V5': ['G2', 'D3', 'G3']}


@theme.section('J', mesures=8)
def J(s):
    t = temps_accords(GRILLE_J)
    nuances(s, ep='mp', harpe='f', celesta='f', pizz_v='mf', pizz_a='mf', pizz_c='f', pizz_b='mf')
    for d, l, c in plages(t):
        for h in NUIT[c]:
            s.note(ep, h, d, l, vel=66)
    arpege_temps(s, harpe, t, 0, s.m(9), NUIT, '1 2 3 2', vel=74, pas=1.0)
    chante(s, MOTIF, s.m(6) - 1, [(celesta, 1)], vel=84)
    oom(s, [pizz_b], t, 1, 8, octave=1, vel=78, plancher='F1')
    oom(s, [pizz_c], t, 1, 8, octave=2, vel=70, plancher='G2')
    pa(s, [pizz_v, pizz_a], t, 1, 8, grave='G3', vel=64)
    s.joue(boite, ANAC.octave(2), a=s.m(8, 4), vel=84)


