# K : la boîte s'éteint (seule, en mineur ; le ressort se détend) ; la relance

@theme.section('K', mesures=8)
def K(s):
    nuances(s, boite='f', peigne='f', pizz_b='f', pizz_c='f')
    # le motif en mineur, puis la tête dont les notes s'espacent (un ritardando écrit : le tempo
    # reste, les notes s'éloignent) ; dessous, les lames graves du peigne, de plus en plus rares
    chante(s, motif_sans_anacrouse(MOTIF), 0, [(boite, 2)], vel=96)
    for h, a, d, v in (('Ab5', 0, 2, 58), ('C5', 2, 1, 52), ('Bb4', 3, 1, 50), ('C5', 4, 2, 56), ('G5', 6, 2, 50),
                       ('C5', 8, 2, 50)):
        s.note(peigne, h, a, d, vel=v)
    s.joue(boite, mel('C6:1.25 G6:1.5 | Ab6:3'), a=s.m(3), vel=86)
    s.note(peigne, 'Eb5', s.m(4), 2, vel=48)
    s.note(peigne, 'Eb6', s.m(5, 2), 2, vel=60)
    s.note(peigne, 'G5', s.m(6, 3), 2, vel=46)
    s.note(peigne, 'C6', s.m(7, 2), 3, vel=50)
    s.diminuendo(boite, s.m(4), s.m(7, 4), 'f', 'mp')
    for m in (1, 2, 3):
        s.note(pizz_b, 'C2', s.m(m), 1, vel=70 - 4 * m)
        s.note(pizz_c, 'C3', s.m(m), 1, vel=62 - 4 * m)
    s.note(pizz_b, 'C2', s.m(5), 1, vel=54)
    # la relance : la cérémonie recommence (le roulement, la cymbale, « fu-si » des cuivres)
    roulement(s, caisse_roul, 'S', s.m(8), s.m(8, 4), 'pp', 'ff', vel=90)
    cymbale_vers(s, s.m(9), 'monte_2s', vel=100)
    s.note(timbales, 'G2', s.m(8, 4), 1, vel=92)
    chante(s, ANAC, s.m(8, 4), [(cors, 0), (trombones, -1), (trompettes, 1)], vel=106)
    nuances(s, cors='f', trombones='f', trompettes='f')
    s.nuance(boite, 'f', s.m(8))


theme.forme(intro=['intro'], corps=['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K'])
