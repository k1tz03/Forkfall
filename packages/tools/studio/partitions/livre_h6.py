def casse(s, de, a, motifs=(CASSE_A, CASSE_A2), relance=True, orchestre=False, vel=96):
    """La batterie cassée, de la mesure `de` à `a` comprise ; `orchestre` : la grosse caisse et la
    caisse claire de l'orchestre doublent les coups forts (le temps 1, le contretemps de 3, 2 et 4)."""
    for m in range(de, a + 1):
        txt = RELANCE if (relance and m == a) else motifs[(m - de) % len(motifs)]
        s.batterie(batterie, txt, a=s.m(m), jusqua=s.m(m + 1), vel=vel)
        if orchestre:
            s.note(gcaisse, 'C4', s.m(m), 1, vel=92)
            s.note(gcaisse, 'C4', s.m(m, 3.5), 1, vel=80)
            s.note(caisse, 'S', s.m(m, 2), 0.5, vel=86)
            s.note(caisse, 'S', s.m(m, 4), 0.5, vel=90)


def sans_anacrouse(motif, anacrouse=1.0):
    """Le motif sans ses deux notes d'appel (une section qui commence sur « BLE ») ; `anacrouse` :
    leur durée (1 temps à sa vitesse, 0,5 en diminution, 2 élargi)."""
    return motif.coupe(anacrouse, motif.longueur)


