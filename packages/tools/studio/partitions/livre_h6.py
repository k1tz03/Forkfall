def moteur(s, piste, temps, de, a, octave=3, figs='abcb', vel=80, pedale_h=None, basse=None, vel_basse=90,
           derniere=4, basse_octave=1):
    """Les doubles croches de la mesure `de` à `a` comprise ; `pedale_h` : sur cette note seule ;
    `basse` frappe les accents à l'octave grave (la basse en octaves)."""
    for m in range(de, a + 1):
        decal, acc = FIGURES[figs[(m - de) % len(figs)]]
        acc = acc.split()
        nb = derniere if m == a else 4
        for i in range(4 * nb):
            t = (m - 1) * 4 + i * 0.25
            r = hauteur(pedale_h) if pedale_h else racine(temps[int(t)], octave, 'C2')
            v = {'X': vel + 20, 'x': vel, 'o': vel - 22}[acc[i]]
            s.note(piste, r + decal[i], t, 0.25, vel=v)
            if basse is not None and acc[i] == 'X':
                b = (hauteur(pedale_h) - 12 * (octave - basse_octave)) if pedale_h else racine(
                    temps[int(t)], basse_octave, 'E1')
                s.note(basse, b, t, 0.5, vel=vel_basse)


def basse_octaves(s, pistes, temps, de, a, vel=88, octave=1, plancher='E1', pedale_h=None, sans_saut=()):
    """La basse en octaves, en croches : grave, aiguë, grave, aiguë… ; sous les accords de `sans_saut`,
    la note grave seule (la pédale ne monte pas frotter la mèche)."""
    for m in range(de, a + 1):
        for i in range(8):
            t = (m - 1) * 4 + i * 0.5
            r = hauteur(pedale_h) if pedale_h else racine(temps[int(t)], octave, plancher)
            h = r if (i % 2 == 0 or temps[int(t)] in sans_saut) else r + 12
            for p in pistes:
                s.note(p, h, t, 0.5, vel=vel if i % 2 == 0 else vel - 10)


def piques(s, piste, temps, de, a, grave='D3', vel=96, rythme='X . . X . . X . . . X . X . . .'):
    """Les accords piqués (le chantage frappé) sur une grille de doubles croches."""
    cases = rythme.split()
    for m in range(de, a + 1):
        for i, c in enumerate(cases):
            if c == '.':
                continue
            t = (m - 1) * 4 + i * 0.25
            for h in voicing(temps[int(t)], grave):
                s.note(piste, h, t, 0.25, vel=vel if c == 'X' else vel - 16)


# --- le fax -------------------------------------------------------------------------------------
# les deux sons du fax selon l'accord : le chant V.21 (1650 / 1850 Hz ≈ la♭6 / si♭6) sur le chantage
# (♭II) ; sur ♭VI, si♭6 et do7 (1850 Hz et la réponse, 2100 Hz) ; ailleurs, le fax se tait
FSK = {'bII': ('Ab6', 'Bb6'), 'bVI': ('Bb6', 'C7')}


def fax_appel(s, a):
    """L'appel (do6, deux bips) puis la réponse (do7, tenue deux temps)."""
    s.note(fax, 'C6', a, 1.0, vel=80)
    s.note(fax, 'C6', a + 2, 1.0, vel=76)
    s.note(fax_ton, 'C7', a + 4, 3.5, vel=90)


def fax_chant(s, temps, de, a, motif='x x . x x . x x x . x x . x . x', vel=78):
    """Le chant du fax en doubles croches, sur les temps dont l'accord contient ses deux sons."""
    cases = motif.split()
    k = 0
    for m in range(de, a + 1):
        for i, c in enumerate(cases):
            x = (m - 1) * 4 + i * 0.25
            paire = FSK.get(temps[int(x)])
            if c == '.' or paire is None:
                continue
            s.note(fax, paire[k % 2], x, 0.2, vel=vel if c == 'x' else vel + 14)
            k += 1


def coupure(s, m, accord_final='bII', arc_aussi=False, vel=118):
    """La dernière mesure d'une nuit : un coup sur le premier temps, puis plus rien que l'horloge
    (à la noire) et le papier qui tombe. Avec l'arc (`arc_aussi`) : pas de papier, l'horloge à la
    blanche et plus bas, et l'arc au 4ᵉ temps, après un temps de silence — la photo s'imprime
    (au 2ᵉ temps, la queue du coup le couvrait : +2,6 dB seulement sur la seconde d'avant)."""
    t = s.m(m)
    for h in voicing(accord_final, 'D3'):
        s.note(tromb_st, h, t, 0.5, vel=vel)
    for h in voicing(accord_final, 'Ab4'):
        s.note(tromp_st, h, t, 0.5, vel=vel - 10)
    s.note(basses, 'D2', t, 0.5, vel=vel)
    s.note(timbales, 'D2', t, 1, vel=vel)
    s.note(gcaisse, 'C4', t, 1, vel=vel - 6)
    s.note(cymbales, 'C4', t, 1, vel=vel - 20, art='etouffee')
    if arc_aussi:
        arc.poser(s, s.m(m, 4), impact=False, vel=118)
        horloge(s, m, m, noire=False, vel=72)
    else:
        s.note(papier, 'C5', t + 1.25, 1.5 * SEC, vel=96)
        horloge(s, m, m, noire=True, vel=90)          # l'horloge seule : un peu plus fort
        # le dernier demi-temps : l'horloge presse encore (une croche) ; la couture de la boucle
        # (L → A) garde ainsi une attaque de chaque côté (+3,9 dB sans elle)
        s.note(horloge_bois, 76, s.m(m, 4.5), 0.25, vel=78)
        s.note(horloge_pizz, TIC, s.m(m, 4.5), 0.25, vel=74)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=90):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def cymbale_vers(s, fin, art='monte_2s', vel=96):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * SEC, secondes * SEC, vel=vel, art=art)


