def temps_accords(mesures):
    sortie = []
    for c in mesures:
        sortie += CELLULES.get(c, [c] * 4)
    return sortie


def sons(ch):
    """Les classes de hauteur de l'accord (« V-5 » : sans la quinte)."""
    base, _, moins = ch.partition('-')
    pcs = [h % 12 for h in accord(base, TON, octave=3)]
    if moins == '5':
        r = fondamentale(base, TON)[0]
        pcs = [p for p in pcs if p != (r + 7) % 12]
    return pcs


def racine(ch, octave, plancher='E1'):
    pc = fondamentale(ch.partition('-')[0], TON)[0]
    h = 12 * (octave + 1) + pc
    while h < hauteur(plancher):
        h += 12
    return h


def voicing(ch, grave):
    g = hauteur(grave)
    sortie = set()
    for pc in sons(ch):
        h = g + ((pc - g) % 12)
        sortie.add(h)
    return sorted(sortie)


def plages(temps):
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def nappe(s, piste, temps, grave, vel=70, art=None, de=0, jusqua=None):
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d < de or d >= fin:
            continue
        for h in voicing(c, grave):
            s.note(piste, h, d, min(l, fin - d), vel=vel, art=art)


