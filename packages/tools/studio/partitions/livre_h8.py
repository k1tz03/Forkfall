@theme.section('intro', mesures=4)
def intro(s):
    nuances(s, voix_f1='fff', voix_f2='fff', voix='mf', cors='mp', vibra='pp', basses='pp', sub='mf', verre='p')
    arc.poser(s, 0, impact=True, vel=118)
    s.note(sub, 'A1', 0.5, 15.5, vel=62)
    s.note(basses, 'A1', 0.5, 15.5, vel=60, art='tenu')
    s.note(verre, 'A4', 1, 15, vel=60)
    s.note(verre, 'E5', 1, 15, vel=56)
    # la voix seule, tout près : la tête ; le cor la répète une mesure plus tard
    chante(s, TETE, s.m(1, 4), vel=94)
    s.joue(cors, TETE, a=s.m(2, 4), vel=84)
    # les triolets s'éveillent (m. 3–4), la cymbale enfle vers A1
    triolets_machine(s, vibra, vel=60, de=3, a=4)
    s.crescendo(vibra, s.m(3), s.m(5), 'pp', 'p')
