# Les accords : la basse, les trois voix tenues (elles bougent peu), le cycle des triolets
# (quatre sons de l'accord, du grave à l'aigu)
# Le cycle de i est la m6 (la do mi fa#) : la machine épelle le triton du motif (do–fa#), et
# rien ne frotte la mèche quand l'orchestre la pose sur i ; celui de ♭VII n'a pas de sol (si ré
# fa# la : la mèche de la clarinette y tombe sans demi-ton).
ACCORDS = {
    'i': ('A1', ('A3', 'C4', 'E4'), ('A4', 'C5', 'E5', 'F#5')),
    'IV': ('D2', ('A3', 'D4', 'F#4'), ('A4', 'C5', 'D5', 'F#5')),
    'bVII': ('G1', ('G3', 'B3', 'D4'), ('B4', 'D5', 'F#5', 'A5')),
    'I': ('A1', ('A3', 'C#4', 'E4'), ('A4', 'C#5', 'E5', 'F#5')),
    '#IV': ('Eb2', ('Bb3', 'Eb4', 'G4'), ('G4', 'Bb4', 'C5', 'Eb5')),
    # i sans do, sous le « do si » de passage de l'orchestre (sinon si contre do)
    'iT': ('A1', ('A3', None, 'E4'), ('A4', 'E5', 'F#5', 'A5')),
    # ♭VII sans sol dans la nappe, sous la mèche de la clarinette (fa# tenu, la laverie)
    'bVIIT': ('G1', (None, 'B3', 'D4'), ('B4', 'D5', 'F#5', 'A5')),
}
GRILLE_D = ['i'] * 4 + ['IV'] * 4 + ['i'] * 4 + ['IV'] * 4 + ['i'] * 4 + ['IV'] * 4 + ['i'] * 4 + ['bVII'] * 4
GRILLE_T = ['I'] * 16 + ['#IV'] * 16
GRILLES = {'C1': GRILLE_T, 'C2': GRILLE_T}
# les habits de chaque section (temps → accord) : sous le « do si » de l'orchestre (canon 1 : le
# 4ᵉ temps de la m. 3 ; canon 2 : de la m. 7) ; les fins qui glissent déjà vers mib (♭VII → ♯IV)
_CANON1 = {11: 'iT'}
_CANON2 = {27: 'iT'}
_GLISSE = {30: '#IV', 31: '#IV'}
VARIANTES = {
    'A1': _CANON1,
    'B1': {**_CANON1, **_GLISSE}, 'B2': {**_CANON1, **_GLISSE},
    'D1': {**_CANON1, **_CANON2},
    'D2': {**_CANON1, **_CANON2, 31: '#IV'},
    'S2': {11: 'iT'},
    'G1': {28: 'bVIIT', 29: 'bVIIT'},
}


def grille_de(s):
    g = list(GRILLES.get(s.section.nom, GRILLE_D))
    for i, c in VARIANTES.get(s.section.nom, {}).items():
        g[i] = c
    return g


def plages(temps, de=0, jusqua=None):
    fin = len(temps) if jusqua is None else int(round(jusqua))
    de = int(round(de))
    sortie = []
    for i, c in enumerate(temps):
        if i < de or i >= fin:
            continue
        if sortie and sortie[-1][2] == c and sortie[-1][0] + sortie[-1][1] == i:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def tenues(s, piste, rangs=(0, 1, 2), octave=0, vel=70, art=None, de=0, jusqua=None):
    """Les voix tenues de la grille ; une voix qui garde sa hauteur ne se réattaque pas."""
    t = grille_de(s)
    fin = len(t) if jusqua is None else int(round(jusqua))
    de = int(round(de))
    for r in rangs:
        debut, h0 = None, None
        for i in range(de, fin + 1):
            x = ACCORDS[t[i]][1][r] if i < fin else None
            h = hauteur(x) + 12 * octave if x is not None else None
            if h != h0:
                if h0 is not None:
                    s.note(piste, h0, debut, i - debut, vel=vel, art=art)
                debut, h0 = i, h


def basse_tenue(s, piste, octave=0, vel=76, art=None, de=0, jusqua=None, glisse=False):
    """La basse de la grille, tenue ; `glisse` : le passage d'un monde à l'autre glisse depuis la
    note précédente (la sous-basse : vers ♯IV, et le retour de ♯IV) — True pour tous les
    changements qui touchent ♯IV."""
    prec = None
    for d, l, c in plages(grille_de(s), de, jusqua):
        h = hauteur(ACCORDS[c][0]) + 12 * octave
        if glisse and (c == '#IV' or prec == '#IV' or (prec is None and c == 'I')):
            s.note(piste, h, d, l, vel=vel, art=art, glisse=True)
        else:
            s.note(piste, h, d, l, vel=vel, art=art)
        prec = c


# la pulsation binaire : des croches sur la basse, l'octave sur les contretemps de 2 et 4
_CROCHES = ([0, 0, 0, 0, 0, 12, 0, 0], 'X o x o X o x x')
_CROCHES2 = ([0, 0, 0, 12, 0, 0, 0, 12], 'X o x o X o x o')


def croches(s, piste, octave=0, vel=78, art='staccato', de=1, a=8, figs=(_CROCHES, _CROCHES2), derniere=4):
    t = grille_de(s)
    for m in range(de, a + 1):
        decal, acc = figs[(m - de) % len(figs)]
        acc = acc.split()
        nb = derniere if m == a else 4
        for k in range(2 * nb):
            c = t[(m - 1) * 4 + k // 2]
            h = hauteur(ACCORDS[c][0]) + 12 * octave + decal[k]
            v = {'X': vel + 18, 'x': vel, 'o': vel - 18}[acc[k]]
            s.note(piste, h, s.m(m) + k * 0.5, 0.5, vel=v, art=art)


def triolets_machine(s, piste, octave=0, vel=70, de=1, a=8, art=None, accent=12, derniere=4):
    """La machine qui calcule : le cycle des quatre sons de l'accord sur des croches de triolet
    (douze par mesure) ; chaque temps commence par un autre son (la permutation)."""
    t = grille_de(s)
    for m in range(de, a + 1):
        nb = derniere if m == a else 4
        for k in range(3 * nb):
            c = t[(m - 1) * 4 + k // 3]
            cyc = ACCORDS[c][2]
            h = hauteur(cyc[k % 4]) + 12 * octave
            v = vel + (accent if k % 3 == 0 else 0)
            s.note(piste, h, s.m(m) + k / 3.0, 1 / 3.0, vel=v, art=art)


def porte_triolets(s, de=0, jusqua=None):
    """Les instants qui hachent la voix : chaque croche de triolet (une piste muette)."""
    fin = s.longueur if jusqua is None else jusqua
    k = 0
    while de + k / 3.0 < fin - 1e-6:
        s.note(triolets, 'H', de + k / 3.0, 1 / 3.0, vel=60)
        k += 1


def chante(s, motif, a, piste=None, vel=92, machine=True):
    """La voix dans l'oreillette (et sa couche de formants)."""
    s.joue(piste or voix, motif, a=a, vel=vel)
    if machine:
        s.joue(voix_f1, motif, a=a, vel=vel)
        s.joue(voix_f2, motif, a=a, vel=vel)


def canon(s, motif, m, orchestre, voix_piste=None, vel_voix=92, machine=True):
    """La voix chante `motif` (anacrouse au 4ᵉ temps de la mesure m), l'orchestre le même une
    mesure plus tard : `orchestre` = [(piste, transposition, vélocité)]."""
    chante(s, motif, s.m(m, 4), piste=voix_piste, vel=vel_voix, machine=machine)
    for piste, tr, v in orchestre:
        s.joue(piste, motif.transpose(tr), a=s.m(m + 1, 4), vel=v)


def semer_grains(s, de, a, n, notes, vel=40, cle=''):
    """Des poussières de glockenspiel à hasard fixe (la graine : la section, son passage, `cle`) ;
    `notes` : des sons de l'accord qui sonne (rien ne frotte)."""
    alea = random.Random(f'{s.section.nom}-{s.fois}-grains{cle}')
    for _ in range(n):
        t = de + alea.random() * (a - de)
        h = hauteur(alea.choice(notes))
        s.note(grains, h, t, 0.25, vel=vel + alea.randint(-8, 8))


def cymbale_vers(s, fin, art='monte_4s', vel=88):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * SEC, secondes * SEC, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=84):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def pulsation(s, de=1, a=8, vel=96):
    """La grosse caisse électronique sur 1 et 3, doublée par la grosse caisse d'orchestre."""
    s.batterie(kick, 'K : X . . . . . . . x . . . . . . .', a=s.m(de), jusqua=s.m(a + 1), vel=vel)
    s.batterie(gcaisse, 'K : X . . . . . . . x . . . . . . .', a=s.m(de), jusqua=s.m(a + 1), vel=vel - 20)


