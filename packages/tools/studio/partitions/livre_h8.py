# --- C : la voix d'ailleurs (la majeur — mib majeur) ---------------------------------------------
def _ailleurs(s, encore):
    nuances(s, sub='ff', verre='f', vibra='mp', voix_hachee='mf', cors='ff', trombones='ff', basses='mp',
            altos='mp', choeur='mp', timbales='f', tic='f', grains='mf')
    s.note(timbales, 'A2', 0, 1, vel=86)
    basse_tenue(s, sub, octave=0, vel=72, glisse=True)
    basse_tenue(s, basses, vel=74, art='tenu')
    for d, l, c in plages(grille_de(s)):
        for h in ACCORDS[c][1]:
            if h is not None:
                s.note(verre, hauteur(h) + 12, d, l, vel=62)
    tenues(s, altos, octave=1, vel=64)
    triolets_machine(s, vibra, vel=62)
    porte_triolets(s)
    # la mèche en la (sur la majeur), puis la mèche à l'autre bout du triton (sur mib majeur)
    # (la voix seule, hachée : ses formants continus effaceraient la découpe)
    canon(s, MECHE, 1, [(cors, 0, 90)], voix_piste=voix_hachee, machine=False)
    canon(s, MECHE_AILLEURS, 5, [(trombones, -12, 92)], voix_piste=voix_hachee, machine=False)
    semer_grains(s, s.m(2), s.m(5), 5 if encore else 3, ['A6', 'C#7', 'E7', 'F#6'], cle='la')
    semer_grains(s, s.m(5), s.m(9), 5 if encore else 3, ['G6', 'Bb6', 'C7', 'Eb7'], cle='mib')
    if encore:
        tenues(s, choeur, octave=1, vel=70)
        s.crescendo(choeur, 0, s.m(8, 4), 'mp', 'f')
        tenues(s, trombones, octave=-1, vel=66, rangs=(0, 1), de=s.m(1), jusqua=s.m(5))
        s.note(timbales, 'Eb2', s.m(5), 1, vel=88)
        s.batterie(tic, 'H : x . x x x . x x x . x x x . x x', a=s.m(5), jusqua=s.m(9), vel=60)


