@theme.section('F3', mesures=8)
def F3(s):
    t = par_mesure(['I'] * 8)
    nuances(s, halo='pp', basses='pp', celles='pp')
    s.note(basses, 'F2', 0, 8, vel=62)
    s.expression(basses, [(0, 'p'), (8, 'pp')])
    s.note(vibra, 'F4', 0, 2, vel=62)
    souffles(s, t, de=1, vel=70, cordes=None, basse=None)
    s.joue(halo, tenue(['C5', 'F5'], 20, vel=52), a=s.m(2))
    # la tête majeure aux cloches, et le célesta lui répond
    cloches_verre(s, TETE_CL, a=s.m(3, 4), vel=80)
    s.joue(celesta, mel('C6:.5 A5:.5 F5:2'), a=s.m(6, 3), vel=56)
    # la relance (la couture : la dernière mesure sonne déjà comme la première de A) : le souffle
    # des cordes revient (m.7), les altos et les clarinettes entrent sur les notes mêmes qui
    # ouvrent A (la3, do4) et les tiennent par-dessus la couture, le carillon monte, le givre
    souffles(s, t, de=7, vel=78, synthe=False, cordes=('pp', 'mp'), basse=('pp', 'mp'), pedale='I')
    # le dernier souffle ne retombe pas : il enfle jusqu'au raccord ; un pizzicato de levée sur do,
    # à la croche d'avant le temps (5 → 1 : le fa de A tombe sur le temps)
    for p in (celles, basses):
        s.expression(p, [(s.m(8, 3), 'p'), (s.m(8, 4.95), 'mp')])
    s.note(basses_pizz, 'C2', s.m(8, 4.5), 0.5, vel=66)
    s.note(altos, 'A3', s.m(8), 4, vel=72)
    s.note(clarinettes, 'C4', s.m(8), 4, vel=72)
    s.crescendo(altos, s.m(8), s.m(8, 4.9), 'pp', 'mp')
    s.crescendo(clarinettes, s.m(8), s.m(8, 4.9), 'pp', 'mp')
    s.note(carillon, 'C5', s.m(8, 1), 4, vel=72, art='monte')
    s.note(givre, 'C4', s.m(7, 3), 5, vel=60)


