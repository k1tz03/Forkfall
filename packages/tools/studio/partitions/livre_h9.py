# l'ostinato des cordes graves : croches groupées 3+3+2 sur la fondamentale, l'octave sur les accents
OST = ([0, 0, 0, 12, 0, 0, 12, 0], 'X x o X x o X x')
OST2 = ([0, 0, 12, 0, 0, 7, 12, 0], 'X x o X o x X o')


def ostinato_croches(s, piste, temps, octave, vel=82, de=1, a=None):
    a = a or s.mesures
    for m in range(de, a + 1):
        dec, acc = (OST, OST2)[(m - de) % 2]
        for i, c in enumerate(acc.split()):
            b = s.m(m) + i * 0.5
            r = racine(temps[int(b)], octave) + dec[i]
            v = {'X': vel + 18, 'x': vel, 'o': vel - 20}[c]
            s.note(piste, r, b, 0.5, vel=v, art='staccato')


