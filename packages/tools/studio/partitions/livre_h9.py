def racine(ch, octave):
    """La fondamentale d'un chiffre (dans fa) à l'octave dite."""
    return accord(ch, TON, octave=octave)[0]


def voicing(ch, grave):
    """Les sons de l'accord, chacun au plus près au-dessus de `grave`."""
    g = hauteur(grave)
    sortie = set()
    for h in accord(ch, TON, octave=2):
        while h < g:
            h += 12
        sortie.add(h)
    return sorted(sortie)


def plages(temps):
    """Les accords temps par temps → [(début, durée, chiffre)], les temps égaux fusionnés."""
    sortie = []
    for i, c in enumerate(temps):
        if sortie and sortie[-1][2] == c:
            d, l, _ = sortie[-1]
            sortie[-1] = (d, l + 1, c)
        else:
            sortie.append((i, 1, c))
    return sortie


def par_mesure(grille_mes):
    """Une grille d'un accord par mesure → les accords temps par temps."""
    return [c for c in grille_mes for _ in range(4)]


def nappe(s, piste, temps, grave, vel=70, art=None, de=0, jusqua=None):
    """Les accords tenus, de `de` à `jusqua` (en temps)."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        for h in voicing(c, grave):
            s.note(piste, h, a, min(d + l, fin) - a, vel=vel, art=art)


def fondamentales(s, piste, temps, octave, vel=80, art=None, de=0, jusqua=None):
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        s.note(piste, racine(c, octave), a, min(d + l, fin) - a, vel=vel, art=art)


# Le souffle : trois souffles par paire de mesures, 3+3+2 noires (le 3+3+2 du thème principal
# en augmentation) ; chacun enfle et retombe, et les cordes graves respirent avec lui
CYCLE = ((0.0, 3.0), (3.0, 3.0), (6.0, 2.0))


def souffles(s, temps, de=1, a=None, vel=84, synthe=True, cordes=('p', 'mp'), basse=('p', 'mp'),
             octave=3, pedale=None):
    """La ventilation des mesures `de` à `a` (comprises) ; `temps` : les accords temps par temps
    de la section (la fondamentale de chaque souffle, ou `pedale`, un chiffre tenu au grave) ;
    `cordes`, `basse` : la nuance basse et haute du soufflet des violoncelles (trémolo) et des
    contrebasses, ou None."""
    a = a or s.mesures
    fin = s.m(a + 1)
    k = 0
    for m in range(de, a + 1, 2):
        for dt, d in CYCLE:
            t = s.m(m) + dt
            if t >= fin - 1e-6:
                break
            d = min(d, fin - t)
            c = pedale or temps[int(t)]
            v = vel + (4 if k % 3 == 0 else -2 if k % 3 == 2 else 0)
            if synthe:
                s.note(souffle, racine(c, octave), t, d, vel=v)
            # les cordes suivent l'harmonie : une note par accord dans le souffle, sous un seul
            # soufflet (sur une pédale, une seule note)
            morceaux = [(t, d, c)] if pedale else _morceaux(temps, t, d)
            if cordes:
                for t1, d1, c1 in morceaux:
                    s.note(celles, racine(c1, 3), t1, d1, vel=68)
                s.expression(celles, [(t, cordes[0]), (t + 0.42 * d, cordes[1]), (t + d - 0.05, cordes[0])])
            if basse:
                for t1, d1, c1 in morceaux:
                    s.note(basses, racine(c1, 2), t1, d1, vel=66)
                s.expression(basses, [(t, basse[0]), (t + 0.42 * d, basse[1]), (t + d - 0.05, basse[0])])
            k += 1


def _morceaux(temps, t, d):
    """Le souffle [t, t + d) coupé aux changements de fondamentale : [(début, durée, chiffre)]."""
    sortie = []
    b = t
    while b < t + d - 1e-6:
        c = temps[int(b)]
        e = b
        while e < t + d - 1e-6 and racine(temps[int(e)], 3) == racine(c, 3):
            e = min(t + d, int(e) + 1.0)
        sortie.append((b, e - b, c))
        b = e
    return sortie


def cloches_verre(s, motif, a, vel=84, glockenspiel=False, synthe=True, celeste=True):
    """Les cloches de verre : le vibraphone, la couche « verre » à l'unisson, le célesta une octave
    au-dessus (à l'unisson, son accord, une dizaine de cents trop haut dans ce registre, battait
    avec le vibraphone à 7–10 Hz), et le glockenspiel à l'octave aux grands moments."""
    s.joue(vibra, motif, a=a, vel=vel)
    if celeste and not glockenspiel:
        s.joue(celesta, motif.octave(1), a=a, vel=vel - 12)
    if synthe:
        s.joue(verre, motif, a=a, vel=vel - 6)
    if glockenspiel:
        s.joue(glock, motif.octave(1), a=a, vel=vel - 18)


def choral(s, a, a_piste, t_piste, b_piste, de=0, jusqua=32, vel=84, b_octave=0, t_octave=0):
    """Les voix d'alto, de ténor et de basse du choral, de `de` à `jusqua` (en temps du choral) ;
    le temps 0 du choral tombe à la position `a` de la section."""
    for piste, voix_, oct_ in ((a_piste, ALTO, 0), (t_piste, TENOR, t_octave), (b_piste, BASSE, b_octave)):
        if piste is None:
            continue
        for n in voix_.notes:
            if n.t + n.d <= de or n.t >= jusqua:
                continue
            d0 = max(n.t, de)
            s.note(piste, n.h + 12 * oct_, a + d0, min(n.t + n.d, jusqua) - d0, vel=vel)


def cymbale_vers(s, fin, art='monte_4s', vel=90):
    secondes = {'monte_2s': 2.0, 'monte_4s': 4.0, 'monte_7s': 7.0}[art]
    s.note(suspendue, 'C4', fin - secondes * 100 / 60.0, secondes * 100 / 60.0, vel=vel, art=art)


def roulement(s, piste, h, de, a, nuance_de, nuance_a, vel=84):
    s.note(piste, h, de, a - de, vel=vel)
    s.expression(piste, [(de, nuance_de), (a, nuance_a)])


def air_haut(s, temps, vel=60, de=0, jusqua=None):
    """L'air : deux notes très aiguës (la quinte ou la tierce, et la fondamentale), en trémolo."""
    fin = len(temps) if jusqua is None else jusqua
    haut = {'i': ('C6', 'F6'), 'i5': ('C6', 'F6'), 'I': ('C6', 'F6'), 'IV': ('D6', 'F6'), 'iv': ('Db6', 'F6'),
            'V': ('C6', 'E6'), 'V7': ('C6', 'E6'), 'bVII': ('Eb6', 'G6')}
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        for h in haut[c]:
            s.note(air, h, a, min(d + l, fin) - a, vel=vel)


def sous_basse(s, temps, vel=72, de=0, jusqua=None):
    """La sous-basse sur les fondamentales, à l'octave 1, jamais sous mi1."""
    fin = len(temps) if jusqua is None else jusqua
    for d, l, c in plages(temps):
        if d >= fin or d + l <= de:
            continue
        a = max(d, de)
        h = racine(c, 1)
        s.note(sub, h + 12 if h < hauteur('E1') else h, a, min(d + l, fin) - a, vel=vel)


# le dôme : i–IV, deux mesures chacun ; au 4e temps de la seconde mesure de i, l'accord s'ouvre en
# quinte à vide (fa do, comme ♭VII à vide sous « do si » dans le thème principal) : le « lab sol »
# du motif y passe sans frotter
DOME = ['i', 'i', 'IV', 'IV', 'i', 'i', 'IV', 'IV']


def dome(grille_mes=DOME):
    """Les accords du dôme, temps par temps (i5 au dernier temps de chaque seconde mesure de i)."""
    temps = par_mesure(grille_mes)
    for m in range(1, len(grille_mes)):
        if grille_mes[m] == 'i' and grille_mes[m - 1] == 'i':
            temps[4 * m + 3] = 'i5'
    return temps


def dome_choeur(s, temps, vel=76, de=0, jusqua=None, art='aah', haut=True):
    """Le chœur immense et lointain sur i–IV (fa au grave : la coupole sur sa pédale), doublé
    par la voix de synthèse."""
    nappe(s, coupole, temps, 'F3', vel=vel, art=art, de=de, jusqua=jusqua)
    if haut:
        nappe(s, coupole, temps, 'C4', vel=vel - 8, art=art, de=de, jusqua=jusqua)
    nappe(s, coupole_voix, temps, 'F3', vel=vel - 6, de=de, jusqua=jusqua)


